"""Representative solo stages for the debug console's testparty (assets_dev/engine/rulesets/maw/debug/test_parties.yml),
from the simulated solo playthroughs: levels 50, 100, 200, 300 and 500 on MAW, Nightmare and Beyond Madness.

For each difficulty and level, the playthrough of seed 1 (route/out_<difficulty>.jsonl) gives:
- the map the solo was clearing when it reached the level (a map with monsters), and every map cleared before it;
- the level banks per continent (MM8 Jadame, MM7 Antagarich, MM6 Enroth, MM9), summed from the maps cleared there;
- the promotion (final class once one continent has 40 % of its maps cleared, as gen_pool.py).
The pool cases of the two-handed Champion (pool_meta.json, the snapshots at levels 10, 50, 200 and 500) give the
weapon skill level, the potion power and the best loot's drop level and rarity, interpolated to 100 and 300.
Stats are gen.py's stats() for a melee build at that level and potion power.

Since 2026-11-15 every stage also carries `builds`: for each solo_* test party, the simulated build written out in
full (the seven stats, the skills with their masteries and the worn kit the simulation chose and crafted from that
playthrough's loot; harness rows `gear`, pool_meta.json `skills`). `testparty` then gives the party exactly that
character and not random rolls. The level, banks and maps are still seed 1's.

Usage: python3 gen_solo_stages.py > solo_stages.yml   (paste between the "solo stages" markers in test_parties.yml)
"""
import bisect, collections, json, statistics, sys
from simdir import S, CODE

sys.argv = ['gen.py', S + '/caps.txt', '/dev/null', '/dev/null']
exec(open(CODE + '/gen.py').read().split("DIFFS = [")[0])   # stats()

MAPS = json.load(open(S + '/inv/maps.json'))
CONTINENT = {'jadame': 0, 'antagarich': 1, 'enroth': 2}
DIFFS = [('maw', 'MAW', 'maw'), ('nightmare', 'Nightmare', 'nightmare'), ('madness', 'Beyond Madness', 'madness')]
LEVELS = [10, 50, 100, 200, 300, 500, 'end']
END = 9999
# Test party -> the simulated build it plays.
PARTY_BUILDS = {'solo_champion': 'knight_2h', 'solo_archer': 'archer', 'solo_archmage': 'archmage',
                'solo_deathknight': 'dk_vampire', 'solo_seraph': 'seraph', 'solo_dragon': 'dragon', 'solo_troll': 'troll',
                'solo_minotaur': 'minotaur_dual'}
STAT_ORDER = ['might', 'intellect', 'personality', 'endurance', 'accuracy', 'speed', 'luck']
