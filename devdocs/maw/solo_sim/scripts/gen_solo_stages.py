RARITY = ['none', 'common', 'uncommon', 'rare', 'epic', 'ancient', 'primordial', 'legendary', 'celestial']
SEED = 1
BUILD = 'knight_2h'
meta = json.load(open(S + '/pool_meta.json'))


def builds_at(dk, stage):
    """Test party -> (stats, skills, worn kit) of its build at the stage (seed 1), from the harness rows."""
    out = {}
    rows = {}
    for line in open(f'{S}/pool_out_{dk}.jsonl'):
        d = json.loads(line)
        rows[d['id']] = d
    for party, build in PARTY_BUILDS.items():
        cid = next((k for k in rows if k.startswith(f'{build}|{stage}|{dk}|s{SEED}')), None)
        if cid is None:
            continue
        m = meta[cid]
        st = stats(BUILD_KIND[build], m['actual_level'], m['P'])
        out[party] = (rows[cid]['level'], [st[k] for k in STAT_ORDER], m['skills'], rows[cid]['gear'])
    return out


def interpolate(points, level):
    keys = sorted(points)
    if level <= keys[0]:
        return points[keys[0]]
    if level >= keys[-1]:
        return points[keys[-1]]
    i = bisect.bisect_left(keys, level)
    lo, hi = keys[i - 1], keys[i]
    t = (level - lo) / (hi - lo)
    a, b = points[lo], points[hi]
    return tuple(x + (y - x) * t if isinstance(x, (int, float)) and not isinstance(x, bool) else (x if t < 0.5 else y)
                 for x, y in zip(a, b))


def main():
    print('  # Solo stages (generated by devdocs/maw/solo_sim/scripts/gen_solo_stages.py from the simulated solo')
    print('  # playthroughs): pair them with a solo_* party and the options of their difficulty, e.g.')
    print('  # `testparty solo_madness_200 solo_champion nightmare beyond_madness horizontal solo`. Each stage\'s `builds`')
    print('  # give those parties the simulation\'s own character: its stats, skills and the kit it chose and crafted.')
    for dk, title, tag in DIFFS:
        lines = [json.loads(l) for l in open(f'{S}/route/out_{dk}.jsonl')]
        traj = next(d['maps'] for d in lines if d['kind'] == 'trajectory' and d['seed'] == SEED)
        snaps = {(d['stage'] if d['stage'] > 0 else END): d for d in lines if d['kind'] == 'snapshot' and d['seed'] == SEED}
        totals = collections.Counter(MAPS[m[0]]['continent'] for m in traj if m[0] in MAPS)
        for L in LEVELS:
            if L == 'end' and 500 not in snaps:   # the run ended below 500: its `_500` stage is the end already
                continue
            stage = END if L == 'end' or L not in snaps else L
            snap = snaps[stage]
            cleared = snap['maps_cleared']
            # The map the solo was clearing when it reached the stage (the last one with monsters).
            index = max(i for i, m in enumerate(traj[:max(cleared, 1)]) if m[1] < 1e7)
            map_file, map_level = traj[index][0], traj[index][1]
            level = max(1, int(snap['char_level']))
            banks = [0.0, 0.0, 0.0, 0.0]
            previous = 0.0
            for m in traj[:index]:
                if m[0] in MAPS:
                    banks[CONTINENT.get(MAPS[m[0]]['continent'], 0)] += max(0.0, m[3] - previous)
                previous = m[3]
            done = collections.Counter(MAPS[m[0]]['continent'] for m in traj[:index] if m[0] in MAPS)
            promoted = any(done[c] / totals[c] >= 0.4 for c in totals)
            builds = builds_at(dk, stage)
            top = [items[-1] for items in snap['pool'].values() if items]
            drop = statistics.median(it[8] for it in top) if top else 1
            rarity = collections.Counter(it[7] for it in top).most_common(1)[0][0] if top else 1
            weapon = max([v[0] for b in builds.values() for k, v in b[2].items() if k in ('Axe', 'Sword', 'Mace', 'Spear', 'Bow')] or [1])
            st = stats('melee', level, 0)
            gold = int(round(level ** 2 * 40, -3))
            kits = ['healing', 'potions'] + (['reagents', 'gems'] if level >= 100 else []) + (
                ['crafting'] if level >= 200 else [])
            completed = [m[0] for m in traj[:index] if m[1] < 1e7]
            print(f'  - id: solo_{tag}_{L}')
            print(f'    title: "Solo, {title}, level {level}: {MAPS.get(map_file, {}).get("name", map_file)}'
                  f' (map level {int(map_level)}, {len(completed)} maps cleared)"')
            print(f'    level: {level}')
            print(f'    skill_level: {int(round(weapon))}')
            print(f'    stats: {int(round(statistics.mean(st.values())))}')
            if promoted:
                print('    promoted: true')
            print(f'    gear: {{level: {int(round(drop))}, rarity: {RARITY[int(rarity)]}}}')
            print(f'    banks: [{", ".join(str(int(round(b))) for b in banks)}]')
            print(f'    gold: {gold}')
            print(f'    food: {min(200, 40 + level // 3)}')
            print(f'    kits: [{", ".join(kits)}]')
            print('    quest_bits: *town_portal')
            print(f'    completed_maps: [{", ".join(completed)}]')
            print(f'    map: {map_file}')
            print('    party: solo_champion')
            if builds:
                print('    builds:')
                for party, (_, values, skills, worn) in builds.items():
                    skill_text = ', '.join(f'{k}: [{v[0]}, {v[1]}]' for k, v in skills.items())
                    print(f'      {party}:')
                    print(f'        stats: [{", ".join(str(int(v)) for v in values)}]')
                    print(f'        skills: {{{skill_text}}}')
                    print(f'        worn: [{", ".join("[" + ", ".join(str(x) for x in item) + "]" for item in worn)}]')
            print()


if __name__ == '__main__':
    main()
