    s=(h9*tr/h7)*(d9/d7)
    print(f"{name:6} s={s:4.2f}  dungeon pack(MM7 3.4): lin {3.4/s:3.1f} quad {quad(s,3.4):3.1f}  outdoor pack(2.5): lin {2.5/s:3.1f} quad {quad(s,2.5):3.1f}")
