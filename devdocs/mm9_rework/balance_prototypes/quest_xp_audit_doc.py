"""Write devdocs/mm9_rework/QUEST_XP_AUDIT.md from the audit table and the quest XP profile. Run from the repository
root after quest_xp_audit.py and quest_xp_profile.py; keeps the hand-written "Alternatives" section of the document."""
import collections, csv, glob, runpy
from pathlib import Path

DOC = Path('devdocs/mm9_rework/QUEST_XP_AUDIT.md')
pr = runpy.run_path('devdocs/mm9_rework/balance_prototypes/quest_xp_profile.py', run_name='x')
rows = list(csv.DictReader(open('output/mm9_balance/quest_xp_audit.tsv'), delimiter='\t'))
prof = {(o[0], o[1], o[2]): o[3] for o in pr['out']}
text = DOC.read_text() if DOC.exists() else ''
alternatives = text[text.index('## Alternatives'):] if '## Alternatives' in text else ''
rude = {}
for f in glob.glob('assets_dev/worlds/mm9/dialogue/rude/NPC*.rude'):
    for r in csv.reader(open(f, encoding='latin-1')):
        if len(r) > 8 and r[0].strip().isdigit():
            rude.setdefault(r[0].strip(), []).append((r[3], [x.strip() for x in r[6:]]))

def what(keys):
    journal, other = [], []
    for npc, rs in rude.items():
        for prompt, nums in rs:
            if any(k in nums for k in keys):
                (journal if npc in ('997', '999') else other).append(prompt)
    journal = [x for x in journal if not x.lower().startswith('blank')]
    return (journal[:1] or other[:1] or [''])[0].replace('|', '/')

FOR = {  # quests whose key text does not name them
    ('isleofashes', 'onsink'): 'Escape the Isle of Ashes', ('sturmfordcity', 'gladiator'): 'Gladiator promotion',
    ('afterworld', 'suffering'): 'Six Fires: suffering', ('afterworld', 'absolution'): 'Six Fires: absolution',
    ('arslegardcity', 'united'): 'Unite the clans (every Jarl)', ('frosgardcity', 'reward'): 'Pledge',
    ('guberland', 'givethjorgardprize'): 'Thjorgard games prize', ('frosgardcity', 'stoptamur'): 'Stop Tamur Leng',
    ('frosgardcity', 'ondeath'): 'Kill Forad Darre after his betrayal',
    ('1000terrors', 'onuse'): 'Win: Njam imprisoned (closing cutscene)', ('hallofthegods', 'stopnjam'): 'Krohn: stop Njam',
    ('arslegardcity', 'onchase'): 'Njam chased in Arslegard',
    ('arslegardcity', 'fadeout'): 'Let into Arslegard with the Writ of Fate',
    ('greatgate', 'exitin'): 'Turned away at the gate (Fateman)', ('verhoffinruins', 'onuse'): 'Pick up the Writ of Fate',
    ('verhoffinruins', 'onplace'): 'Place the Capstone of Order', ('darkpassageway', 'darkpass'): "Igrid's Dark Passageway",
}
groups = collections.defaultdict(list)
tot, new_tot, count = collections.Counter(), collections.Counter(), collections.Counter()
for r in rows:
    key = (r['map'], r['routine'].lower(), int(r['xp']))
    chapter = pr['CONTENT_CHAPTER'].get(key, int(r['chapter']))
    promotion = bool(pr['PROMOTION'].search(r['routine'])) or key in pr['PROMOTION_ROWS']
    new = prof.get((r['script'], r['routine'], int(r['xp'])), int(r['xp']))
    label = FOR.get((r['map'], r['routine'].lower())) or what(r['keys checked'].split() + r['keys given'].split()) \
        or r['routine']
    if r['map'] == 'darkpassageway' and int(r['xp']) == 146000:
        label = 'Capstone of Order obtained (Thorir, the capstone or Igrid: one of three)'
    groups[chapter].append((int(r['xp']), new, r['map'], r['npc'], r['routine'], label, promotion, int(r['gold'])))
    tot[chapter] += int(r['xp']); new_tot[chapter] += new; count[chapter] += 1
L, K = pr['CHAPTER_LEVEL'], pr['AWARD_CAP_LEVELS']
lines = []
for chapter in range(1, 6):
    lines.append(f"\n### Chapter {chapter} (content level {L[chapter]}, cap {int(K[chapter] * 1000 * L[chapter]):,}): "
                 f"{tot[chapter]:,} → {new_tot[chapter]:,}\n")
    lines.append('| Map | Giver (routine) | For | Original | New | Gold |\n| --- | --- | --- | --- | --- | --- |')
    for x, new, mid, npc, routine, label, promotion, gold in sorted(groups[chapter], key=lambda g: -g[0]):
        shown = f'**{new:,}**' if new != x else f'{new:,}'
        lines.append(f"| {mid} | {npc} ({routine}) | {label[:80]}{' (promotion)' if promotion else ''} | {x:,} | "
                     f"{shown} | {gold:,} |")
summary = '\n'.join(f'| {c} | {L[c]} | {int(K[c] * 1000 * L[c]):,} | {tot[c]:,} | {new_tot[c]:,} |' for c in range(1, 6))
doc = f"""# MM9 quest XP audit (2026-11-06)

Every experience award in the original MM9 scripts, what it is for, where the work is, and its balanced amount. Part of
[BALANCE_PLAN.md](BALANCE_PLAN.md) section 3.1; **status: decided 2026-11-06**, implemented in
`tools/mm9_import_discovery/mm9_quest_xp_profile.yml` and `mm9_scr_to_lua.py`. Generated by
`balance_prototypes/quest_xp_audit_doc.py` (the "Alternatives" section is hand-written and kept).

Sources: the `GiveExp` commands in the original SCR scripts and their include files (`mm9/extracted/SCRIPTS/SCRIPTS/`,
through `assets_dev/worlds/mm9/events/*.script_ir.yml`), the giver's name from the map objects, and the quest from the
journal and dialogue rows that use the award's quest keys (`balance_prototypes/quest_xp_audit.py`, raw table
`output/mm9_balance/quest_xp_audit.tsv`). An award paid in several places (the Orb of Linking in five banks) or from
alternative branches of one script is counted once.

## The rule

- An award pays at most **1.5 levels' worth in chapters 1–2 and 0.5 from chapter 3**; a promotion at most 1.5 levels'
  worth. One level's worth is 1,000 × the level; the level is the count-weighted monster level of the chapter the quest's
  work belongs to; no award is cut below 2,000.
- With these caps the party levels at the pace that keeps the balance probe's fights at MM7's cost (BALANCE_PLAN.md
  sections 1 and 4) and ends near level 69. With MM9's original amounts it would end near level 98, far above MM9's
  monsters from chapter 3.
- Early quests are small and keep their amounts: the Isle of Ashes pays 800–5,200, Sturmford and Drangheim 2,000–15,200.

| Chapter | Content level | Award cap | Original | Balanced |
| --- | --- | --- | --- | --- |
{summary}
| All ({sum(count.values())} awards) | | | {sum(tot.values()):,} | {sum(new_tot.values()):,} |

MM7 for comparison: about 1.7M per member (1.4M quests on one Light/Dark branch, 0.3M promotions). A party of five takes
about four first-tier and four second-tier MM9 promotions of the twelve listed. Awards whose work is in another chapter
than the map that pays them are placed at their work (Stop Tamur Leng is paid in Frosgard City but is endgame; Markel's
Dook quest is chapter 3, Dook's Castle).

Small awards that take their amount from map object parameters (`TM_HARDROCK.scr`: Thjorad Mine's cave-in and dwarves
5,000 each, the Yobboes 6,000, the Isle of Ashes' bone thrashers 200) or a variable (Yanmir's death, 8,000 or 5,000) are
kept and not in the tables.

## Awards by chapter

Bold: changed by the rule.
""" + '\n'.join(lines) + '\n\n' + alternatives
DOC.write_text(doc)
print(sum(tot.values()), sum(new_tot.values()))
