"""Writes tests/scenarios/solo_balance/anchor_<difficulty>_<stage>.yml: a lone test-party character (MAW's `testparty`
stages) on native maps: its attack report against a C-tier native and the hit points it loses to a pack of B-tier
natives in 1- and 3-second windows after a 2-second approach.

Run from anywhere; the scenarios then run from the repository root (see devdocs/solo_action/BALANCE_AND_TALENTS.md
section 9)."""
import os
import sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..'))
OUT = ROOT + '/tests/scenarios/solo_balance/'
MAPS = {  # map: (C-tier target for the attack report, B-tier pack monster, name)
    'out02.odm': (195, 194, 'Ravenshore: Mercenary Captain / Mercenaries'),
    'out03.odm': (33, 32, 'Alvar: Ogre Warleader / Ogre Warriors'),
    'out04.odm': (93, 92, 'Ironsand Desert: Cyclops Warrior / Cyclops Hunters'),
    'out07.odm': (111, 110, 'Murmurwoods: Unicorn Herd Leader / Unicorns'),
    'out08.odm': (33, 32, 'Ravage Roaming: Ogre Warleader / Ogre Warriors'),
    'out05.odm': (192, 191, 'Garrote Gorge: Young Dragon / Dragonettes'),
    'elemf.odm': (75, 74, 'Plane of Fire: Greater Fire Elemental / Fire Elementals'),
    'pbp.odm': (156, 155, 'Plane Between Planes: Ether Lord / Ether Champions'),
}
PLAN = {
    'nightmare': {'early': ['out02.odm', 'out03.odm'], 'mid': ['out02.odm', 'out03.odm', 'out08.odm', 'out05.odm'],
                  'late': ['out03.odm', 'out08.odm', 'out05.odm', 'elemf.odm'],
                  'endgame': ['out05.odm', 'elemf.odm', 'pbp.odm'], 'extreme': ['elemf.odm']},
    'madness': {'early': ['out02.odm', 'out04.odm'], 'mid': ['out02.odm', 'out04.odm', 'out07.odm'],
                'late': ['out04.odm', 'out07.odm', 'out05.odm'], 'endgame': ['out07.odm', 'out05.odm', 'elemf.odm'],
                'extreme': ['out05.odm', 'elemf.odm', 'pbp.odm']},
}
RULESET = {'nightmare': '{id: maw, difficulty: nightmare, progression: horizontal}',
           'madness': '{id: maw, difficulty: nightmare, challenge_mode: beyond_madness}'}
PACK = {'nightmare': 3, 'madness': 4}
for difficulty, stages in PLAN.items():
    for stage, maps in stages.items():
        lines = [f'id: solo_balance.anchor_{difficulty}_{stage}',
                 f'title: "Solo balance - lone Champion, {stage} stage, {difficulty}: damage dealt and taken"',
                 'world: mm8', 'mode: faithful', 'tags: [solo_balance, maw, measurement]',
                 '# A measurement for devdocs/solo_action/BALANCE_AND_TALENTS.md, not a regression test. Generated by',
                 '# model/gen_anchor.py; model/parse_anchor.py reads the CONSOLE and "party_attack report" lines. Each map:',
                 f'# the C-tier native takes 60 attacks (healed after each), then {PACK[difficulty]} B-tier natives hit the',
                 '# character in 1- and 3-second windows from full hit points, after a 2-second approach.', 'steps:',
                 '  - new_game_flow:', '      start_map: out01.odm', '      member_count: 1',
                 f'      ruleset: {RULESET[difficulty]}',
                 f'  - console: {{line: "testparty apply {stage} solo", expect_contains: "items worn"}}']
        for m in maps:
            c, b, name = MAPS[m]
            lines += [f'  # {name}', f'  - load_map: {{map: {m}}}',
                      '  - console: {line: "actor kill 200000"}',
                      '  - console: {line: "player sheet"}', '  - console: {line: "hp show"}',
                      f'  - spawn_actor: {{monster_id: {c}, near_party: true}}',
                      '  - party_attack: {actor_index: last, count: 60, report: true}',
                      '  - console: {line: "actor kill 200000"}',
                      f'  - spawn_actor: {{monster_id: {b}, near_party: true, count: {PACK[difficulty]}}}']
            # Approach without loss (Immortal), then 1-second and 3-second windows from full hit points.
            lines += ['  - setup_shortcut: {kind: immortal, value: true}', '  - advance_runtime: {seconds: 2}',
                      '  - setup_shortcut: {kind: immortal, value: false}']
            for seconds in (1, 1, 1, 3, 3):
                lines += ['  - console: {line: "hp full"}', f'  - advance_runtime: {{seconds: {seconds}}}',
                          '  - console: {line: "hp show"}']
            lines += ['  - console: {line: "actor kill 200000"}', '  - console: {line: "hp full"}']
        open(OUT + f'anchor_{difficulty}_{stage}.yml', 'w').write('\n'.join(lines) + '\n')
print('ok')
