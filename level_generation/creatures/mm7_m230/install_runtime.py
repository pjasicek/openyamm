"""Install the accepted m230 atlas as custom crusaders, keeping native monsters and BMPs intact."""
from pathlib import Path
import csv
import io
import json
import re
import shutil
import subprocess
import sys

import yaml

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[2]
ASSETS = REPO / 'assets_dev/engine'
VARIANTS = [(901, 259, 'green', 'm900'), (902, 260, 'blue', 'm901'), (903, 261, 'red', 'm902')]


def install():
    source = json.loads((ROOT / 'manifest.json').read_text())
    # Reject collisions before changing any files, including reruns in a growing merged registry.
    owned_families = {v[3] for v in VARIANTS}
    for path in (ASSETS / 'rendering/sprite_frames').rglob('*.yml'):
        text = path.read_text()
        if path.stem in owned_families:
            assert 'atlas:crusader/' in text, f'Occupied sprite family: {path}'
        else:
            assert not any(30000 <= int(value) <= 30101 for value in
                           re.findall(r'\bsprite_id:\s*(\d+)', text)), f'Occupied sprite range: {path}'
    for filename in ['monster_descriptors.txt', 'monster_data.txt']:
        with (ASSETS / 'data_tables' / filename).open(encoding='cp1252') as stream:
            rows = {int(row[0]): row for row in csv.reader(stream, delimiter='\t') if row and row[0].isdigit()}
        for monster_id, native_id, _, _ in VARIANTS:
            assert native_id in rows, f'Missing source monster: {native_id}'
            assert monster_id not in rows or 'custom:crusader_' in '\t'.join(rows[monster_id]), \
                f'Occupied monster id: {monster_id}'
    target = REPO / 'assets_source/engine/sprites_new/crusader'
    (target / 'atlas').mkdir(parents=True, exist_ok=True)
    runtime = {key: source[key] for key in ['schema_version', 'logical_canvas', 'logical_pivot',
                                          'pixels_per_logical_pixel', 'frames', 'variants']}
    runtime['creature'] = 'custom:crusader'
    runtime['recolor_model'] = 'green_chroma_srgb_v1'
    runtime['pages'] = [{key: page[key] for key in ['base', 'mask', 'size']} for page in source['pages']]
    runtime['frames'] = {name: {key: frame[key] for key in ['page', 'atlas_xywh', 'crop_origin_px']}
                         for name, frame in source['frames'].items()}
    runtime['animation_source'] = 'engine/rendering/sprite_frames/monsters/m900.yml through m902.yml'
    for page in runtime['pages']:
        for key in ['base', 'mask']:
            shutil.copy2(ROOT / page[key], target / page[key])
    (target / 'manifest.json').write_text(json.dumps(runtime, indent=2) + '\n')
    subprocess.run([sys.executable, str(REPO / 'tools/cook_sprite_atlases.py'),
                    '--profile', 'desktop', '--family', 'crusader'], cwd=REPO, check=True)
    # Native frame-table playback remains authoritative: timings, octants and reuse are unchanged.
    next_frame = 30000
    for monster_id, native_id, color, family in VARIANTS:
        original_family = f'm{231 + native_id - 259}'
        groups = yaml.safe_load((ASSETS / f'rendering/sprite_frames/monsters/{original_family}.yml').read_text())
        for group in groups['sprites']:
            group['sprite_id'] = next_frame
            group['sprite_name'] = family + group['sprite_name'][-1]
            next_frame += len(group['frames'])
            for frame in group['frames']:
                frame['texture_name'] = 'atlas:crusader/' + frame['texture_name']
        output = ASSETS / f'rendering/sprite_frames/monsters/{family}.yml'
        if output.exists():
            assert 'atlas:crusader/' in output.read_text(), f'Occupied sprite family: {family}'
        output.write_text('# Custom crusader atlas; generated by mm7_m230/install_runtime.py.\n'
                          + yaml.safe_dump(groups, sort_keys=False))
    for filename in ['monster_descriptors.txt', 'monster_data.txt']:
        path = ASSETS / 'data_tables' / filename
        original = path.read_bytes().decode('cp1252')
        lines = original.splitlines(keepends=True)
        rows = list(csv.reader(io.StringIO(original), delimiter='\t'))
        indexed = {int(row[0]): row for row in rows if row and row[0].isdigit()}
        owned = {row[0] for row in VARIANTS}
        for monster_id in owned:
            if monster_id in indexed:
                assert ('custom:crusader_' in '\t'.join(indexed[monster_id])), f'Occupied monster id: {monster_id}'
        lines = [line for line in lines if not (line.split('\t')[0].isdigit()
                 and int(line.split('\t')[0]) in owned)]
        text = ''.join(lines).rstrip('\r\n') + '\r\n'
        for monster_id, native_id, color, family in VARIANTS:
            row = indexed[native_id].copy()
            row[0] = str(monster_id)
            internal = 'custom:crusader_' + color
            if filename == 'monster_descriptors.txt':
                row[1] = internal
                row[11:19] = [family + suffix for suffix in ['s', 'w', 'a', 'a', 'n', 'd', 'x', 'f']]
            else:
                row[1] = 'Crusader (' + color.title() + ')'
                row[2] = internal
            stream = io.StringIO()
            csv.writer(stream, delimiter='\t', lineterminator='\r\n').writerow(row)
            text += stream.getvalue()
        path.write_bytes(text.encode('cp1252'))
    print(json.dumps({'asset_root': str(target), 'monster_ids': [v[0] for v in VARIANTS],
                      'sprite_frame_range': [30000, next_frame - 1], 'atlas_pages': len(runtime['pages'])}))


if __name__ == '__main__':
    install()
