for face in src.data.polygons:
    for li, vi in zip(face.loop_indices, face.vertices):
        vertex_uvs.setdefault(vi, []).append(suv[li].uv.copy())
for i, point in enumerate(S):
    vertex_tree.insert(Vector(point), i)
vertex_tree.balance()
