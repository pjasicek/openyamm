"""Install restored MM6 mages as additional monsters with native combat and animation data."""
import copy
import csv
import io
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys

import yaml

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[2]
ASSETS = REPO / 'assets_dev/engine'
VARIANTS = [(904, 610, 'red', 'm903'), (905, 611, 'green', 'm904'), (906, 612, 'blue', 'm905')]
FIRST_FRAME = 30102


def install():
    source = json.loads((ROOT / 'manifest.json').read_text())
    common_path = ASSETS / 'rendering/sprite_frame_data_common.yml'
    native_groups = yaml.safe_load(common_path.read_text())['sprites']
    groups_by_name = {group['sprite_name']: group for group in native_groups}
    tables = {}
    for filename in ['monster_data.txt', 'monster_descriptors.txt']:
        path = ASSETS / 'data_tables' / filename
        original = path.read_bytes().decode('cp1252')
        rows = {int(row[0]): row for row in csv.reader(io.StringIO(original), delimiter='\t')
                if row and row[0].isdigit()}
        for identity, native, color, _ in VARIANTS:
            assert native in rows
            assert identity not in rows or 'custom:pmn2_' + color in rows[identity], 'Monster ID collision'
        tables[filename] = (original, rows)

    generated = {}
    next_frame = FIRST_FRAME
    for identity, native, color, family in VARIANTS:
        descriptor = tables['monster_descriptors.txt'][1][native]
        group_names = list(dict.fromkeys(descriptor[11:19]))
        names = {name: family + name[4:] for name in group_names}
        groups = []
        for name in group_names:
            group = copy.deepcopy(groups_by_name[name])
            group['sprite_name'] = names[name]
            group['sprite_id'] = next_frame
            next_frame += len(group['frames'])
            for frame in group['frames']:
                texture = frame['texture_name']
                expected = [texture] if 'Image1' in frame['flags'] else [texture + str(i) for i in range(5)]
                assert all(name in source['frames'] for name in expected), expected
                assert str(frame['palette_id']) in source['variants']
                frame['texture_name'] = 'atlas:pmn2/' + texture
            groups.append(group)
        generated[family] = {'sprites': groups}

    # Check the complete common/split frame tables before claiming any new IDs.
    for path in (ASSETS / 'rendering').rglob('*.yml'):
        text = path.read_text()
        if path == ASSETS / ('rendering/sprite_frames/monsters/' + path.stem + '.yml') and path.stem in generated:
            assert 'atlas:pmn2/' in text, 'Sprite family collision: ' + str(path)
            continue
        assert not any(FIRST_FRAME <= int(value) < next_frame for value in
                       re.findall(r'\bsprite_id:\s*(\d+)', text)), 'Sprite ID collision: ' + str(path)

    runtime = {key: source[key] for key in ['schema_version', 'pixels_per_logical_pixel',
                                           'logical_canvas', 'logical_pivot', 'variants']}
    runtime.update(creature='custom:pmn2', recolor_model='masked_luminance_rgb_v1')
    runtime['pages'] = [{key: page[key] for key in ['base', 'mask', 'size']} for page in source['pages']]
    runtime['frames'] = {name: {key: frame[key] for key in ['page', 'atlas_xywh', 'crop_origin_px']}
                         for name, frame in source['frames'].items()}
    target = REPO / 'assets_source/engine/sprites_new/pmn2'
    (target / 'atlas').mkdir(parents=True, exist_ok=True)
    for page in runtime['pages']:
        for key in ['base', 'mask']:
            shutil.copy2(ROOT / page[key], target / page[key])
    (target / 'manifest.json').write_text(json.dumps(runtime, indent=2) + '\n')
    subprocess.run([sys.executable, str(REPO / 'tools/cook_sprite_atlases.py'),
                    '--profile', 'desktop', '--family', 'pmn2'], cwd=REPO, check=True)
    for family, groups in generated.items():
        path = ASSETS / ('rendering/sprite_frames/monsters/' + family + '.yml')
        path.write_text('# Custom mage atlas; generated by mm6_pmn2/install_runtime.py.\n'
                        + yaml.safe_dump(groups, sort_keys=False))

    owned = {entry[0] for entry in VARIANTS}
    for filename, (original, rows) in tables.items():
        lines = [line for line in original.splitlines(keepends=True)
                 if not (line.split('\t')[0].isdigit() and int(line.split('\t')[0]) in owned)]
        text = ''.join(lines).rstrip('\r\n') + '\r\n'
        for identity, native, color, family in VARIANTS:
            row = rows[native].copy()
            row[0] = str(identity)
            if filename == 'monster_descriptors.txt':
                row[1] = 'custom:pmn2_' + color
                row[11:19] = [family + name[4:] for name in row[11:19]]
            else:
                row[2] = 'custom:pmn2_' + color
                # Name, attacks, spell chances/skills, resistances and all balance fields stay native.
                assert row[3:] == rows[native][3:]
                # MM6 native rows now provide explicit biological material defaults for shared blood FX.
                row[8] = '1'
            stream = io.StringIO()
            csv.writer(stream, delimiter='\t', lineterminator='\r\n').writerow(row)
            text += stream.getvalue()
        (ASSETS / 'data_tables' / filename).write_bytes(text.encode('cp1252'))
    print(json.dumps({'monster_ids': sorted(owned), 'sprite_frame_range': [FIRST_FRAME, next_frame - 1],
                      'runtime': str(target), 'pages_shared_by_variants': len(runtime['pages'])}))


if __name__ == '__main__':
    install()
