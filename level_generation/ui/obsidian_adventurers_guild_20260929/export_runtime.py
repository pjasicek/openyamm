"""Fit the generated guild panel using nine-slicing; export native vector arrow states."""
from pathlib import Path
import hashlib
import json
import subprocess

from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = ROOT / "assets_dev/engine/icons_x2"

source = HERE / "art/guild-panel-master.png"
master = Image.open(source).convert("RGBA")
width, height = master.size
cut = 176
corner = 56
target_width, target_height = 920, 688
panel = Image.new("RGBA", (target_width, target_height))
sx, sy = [0, cut, width - cut, width], [0, cut, height - cut, height]
dx, dy = [0, corner, target_width - corner, target_width], [0, corner, target_height - corner, target_height]
for row in range(3):
    for column in range(3):
        patch = master.crop((sx[column], sy[row], sx[column + 1], sy[row + 1]))
        patch = patch.resize((dx[column + 1] - dx[column], dy[row + 1] - dy[row]), Image.Resampling.LANCZOS)
        panel.paste(patch, (dx[column], dy[row]))
panel_path = OUT / "obsidian_guild_panel.png"
panel.save(panel_path)
assets = [panel_path]

# These are code-native control glyphs, following the existing Obsidian controls.
# The painted guild stone is generated by imagegen, never painted or extracted here.
for direction in ("up", "down"):
    points = "5,10 8.5,6.5 12,10" if direction == "up" else "5,7 8.5,10.5 12,7"
    for state, edge, ink, fill in [
        ("normal", "#80775d", "#d1c095", "#111c18"),
        ("hover", "#c0ab79", "#ffebbf", "#233129"),
        ("pressed", "#a68c5e", "#e8d1a4", "#0a120f"),
        ("disabled", "#434b3d", "#60665a", "#111a16"),
    ]:
        svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="34" height="34" viewBox="0 0 17 17">
<rect x=".5" y=".5" width="16" height="16" rx="1.5" fill="{fill}" stroke="{edge}"/>
<rect x="1.8" y="1.8" width="13.4" height="13.4" rx=".6" fill="none" stroke="#344238" stroke-width=".5"/>
<polyline points="{points}" fill="none" stroke="{ink}" stroke-width="1.2" stroke-linejoin="round" stroke-linecap="round"/>
</svg>'''
        vector_path = HERE / "art" / f"arrow-{direction}-{state}.svg"
        vector_path.write_text(svg + "\n")
        path = OUT / f"obsidian_guild_{direction}_{state}.png"
        # Render the same small vector directly: this host's MSVG delegate drops strokes.
        draw = (f'scale 4,4 fill "{fill}" stroke "{edge}" stroke-width 1 '
                'roundrectangle 0.5,0.5 16.5,16.5 1.5,1.5 '
                'fill none stroke "#344238" stroke-width 0.5 '
                'roundrectangle 1.8,1.8 15.2,15.2 0.6,0.6 '
                f'stroke "{ink}" stroke-width 1.2 stroke-linejoin round stroke-linecap round polyline {points}')
        subprocess.run(["magick", "-size", "68x68", "xc:none", "-draw", draw,
                        "-resize", "34x34", "PNG32:" + str(path)], check=True)
        assets.append(path)

receipt = {
    "generation_mode": "built-in imagegen",
    "prompt": "art/prompt.txt",
    "master": {"path": str(source.relative_to(ROOT)), "size": list(master.size),
               "sha256": hashlib.sha256(source.read_bytes()).hexdigest()},
    "nine_slice": {"source_corner_pixels": cut, "runtime_corner_pixels": corner},
    "assets": [],
}
for path in assets:
    path.chmod(0o644)
    image = Image.open(path)
    receipt["assets"].append({"path": str(path.relative_to(ROOT)), "size": list(image.size),
                              "bytes": path.stat().st_size,
                              "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
(HERE / "native/export.json").write_text(json.dumps(receipt, indent=2) + "\n")
print(f"Exported {len(assets)} assets; panel {target_width} x {target_height} (2x logical).")
