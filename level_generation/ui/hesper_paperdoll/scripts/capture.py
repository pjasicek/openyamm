"""Desktop captures of the character screen with Hesper equipment worn, on all five doll types.

    python3 scripts/capture.py <name> <slot>=<item id> [...] [--weapon <item id>] [--jewellery]
    python3 scripts/capture.py <name> --sheet-only        rebuild the sheet from the captures
    python3 scripts/capture.py --family <sheet> <capture>=<label> [...]
                                                          one sheet of several captures: a row per capture, a column
                                                          per doll type (review/desktop/<sheet>.jpg)

A headless scenario (scenarios/<name>.yml, from output/hesper_stage/scenario_run) seeds a party of five, one member
per doll type (human male, human female, minotaur, troll, dwarf), equips the named items (the party fixture equips
without skills; a minotaur takes no helm or boots) and saves; the minimized desktop wrapper loads that save and a
menu tour opens each member's character screen and captures it (`--jewellery`: also its jewellery panel, where
gauntlets are drawn). Writes review/desktop/<name>/ and its sheet.jpg.
"""
import os
import subprocess
import sys
from pathlib import Path

import yaml
from PIL import Image, ImageDraw

PROJECT = Path(__file__).resolve().parents[1]
ROOT = PROJECT.parents[2]
STAGE = ROOT / 'output/hesper_stage'
LOCKS = STAGE / 'locks'
# One member per doll type: the previewer's representative characters (character_data id = portrait id + 1).
MEMBERS = ((0, 'Male', 0), (1, 'Female', 1), (2, 'Minotaur', 20), (3, 'Troll', 22), (4, 'Dwarf', 61))
NO_MINOTAUR = {'helm', 'boots'}


def main():
    name, *rest = sys.argv[1:]
    if rest == ['--sheet-only']:
        return sheet(name)
    if name == '--family':
        return family(rest[0], [pair.split('=', 1) for pair in rest[1:]])
    weapon = None
    jewellery = '--jewellery' in rest
    rest = [value for value in rest if value != '--jewellery']
    if '--weapon' in rest:
        index = rest.index('--weapon')
        weapon = int(rest[index + 1])
        del rest[index:index + 2]
    loadout = {slot: int(item) for slot, item in (pair.split('=') for pair in rest)}
    members = []
    for doll_type, label, portrait in MEMBERS:
        equipment = {slot: item for slot, item in loadout.items() if not (doll_type == 2 and slot in NO_MINOTAUR)}
        if weapon:
            equipment['main_hand'] = weapon
        members.append({'name': label, 'class': 'Knight', 'level': 1, 'portrait_id': portrait,
                        'skills': [{'name': 'Sword', 'level': 1, 'mastery': 1}], 'equipment': equipment})
    scenario = PROJECT / 'scenarios' / f'{name}.yml'
    scenario.parent.mkdir(exist_ok=True)
    scenario_id = f'hesper.paperdoll.{name}'
    scenario.write_text('# Generated by scripts/capture.py: a party wearing Hesper equipment, saved for the desktop '
                        'capture.\n' + yaml.safe_dump({
                            'id': scenario_id, 'world': 'hesper', 'mode': 'faithful',
                            'steps': [{'new_game_flow': {'start_map': 'hes_out1.odm',
                                                         'party': {'gold': 0, 'food': 10, 'members': members}}},
                                      {'save_game': {'name': name}}]}, sort_keys=False))
    log = PROJECT / 'review/desktop' / name
    log.mkdir(parents=True, exist_ok=True)
    # The scenario runner removes its saves at the end unless OPENYAMM_SCENARIO_SAVE_DIR names a folder to keep.
    saves = Path('/tmp/openyamm_scenario_saves') / scenario_id.replace('.', '_')
    with (log / 'scenario.log').open('w') as stream:
        subprocess.run(['flock', '-s', str(LOCKS / 'stage.lock'), 'flock', '-s', str(LOCKS / 'engine_build.lock'),
                        'timeout', '300', str(ROOT / 'build/game/openyamm'), '--world', 'hesper',
                        '--headless-run-scenario', str(scenario), '--scenario-no-color'],
                       cwd=STAGE / 'scenario_run', stdout=stream, stderr=subprocess.STDOUT, check=True,
                       env={**os.environ, 'OPENYAMM_SCENARIO_SAVE_DIR': str(saves)})
    save = saves / f'{name}.oysav'
    steps = [{'wait': 3}, {'expect': 'gameplay'}, {'action': 'quest'}, {'wait': 1.5}]
    for index, (_, label, _) in enumerate(MEMBERS):
        if index:
            steps += [{'action': 'char_cycle'}, {'wait': 1}]
        steps.append({'capture': f'{index}_{label.lower()}'})
        if jewellery:                                   # the magnifier toggles the jewellery panel
            steps += [{'click': [1358, 612]}, {'wait': 1}, {'capture': f'{index}_{label.lower()}_jewellery'},
                      {'click': [1358, 612]}, {'wait': 1}]
    tour = log / 'tour.yml'
    tour.write_text('# Generated by scripts/capture.py.\n'
                    + yaml.safe_dump({'output_dir': str(log), 'exit': True, 'steps': steps}, sort_keys=False))
    with (log / 'game.log').open('w') as stream:
        subprocess.run(['flock', '-s', str(LOCKS / 'engine_build.lock'), 'flock', '-s', str(LOCKS / 'stage.lock'),
                        './tools/run_game.sh', '--isolated', 'paperdoll_' + name, '--world', 'hesper',
                        '--assets', str(STAGE / 'assets_editor_dev'), '--save', str(save),
                        '--set', 'debug.menu_input_tour_path=' + str(tour), '--warmup', '1', '--seconds', '60'],
                       cwd=ROOT, stdout=stream, stderr=subprocess.STDOUT, check=True, timeout=300)
    sheet(name)


def doll_panels(name):
    log = PROJECT / 'review/desktop' / name
    shots = [log / f'{index}_{label.lower()}.png' for index, (_, label, _) in enumerate(MEMBERS)]
    images = [Image.open(shot).convert('RGB') for shot in shots]
    width, height = images[0].size
    crop = (int(width * 0.672), int(height * 0.05), int(width * 0.875), int(height * 0.765))   # the doll panel
    return [image.crop(crop) for image in images]


def family(name, rows):
    """Several captures on one sheet, labelled per row, at half size."""
    grid = [[cell.resize((cell.width // 2, cell.height // 2), Image.Resampling.LANCZOS) for cell in doll_panels(capture)]
            for capture, _ in rows]
    cell_width, cell_height = grid[0][0].size
    label_width = 150
    sheet = Image.new('RGB', (label_width + cell_width * len(MEMBERS), 20 + cell_height * len(rows)), (25, 25, 30))
    draw = ImageDraw.Draw(sheet)
    for column, (_, label, _) in enumerate(MEMBERS):
        draw.text((label_width + column * cell_width + 6, 4), label, fill='white')
    for row, ((_, label), cells) in enumerate(zip(rows, grid)):
        y = 20 + row * cell_height
        for line, text in enumerate(label.split('|')):
            draw.text((6, y + 8 + line * 14), text, fill='white')
        for column, cell in enumerate(cells):
            sheet.paste(cell, (label_width + column * cell_width, y))
    path = PROJECT / 'review/desktop' / f'{name}.jpg'
    sheet.save(path, quality=90)
    print(path)


def sheet(name):
    log = PROJECT / 'review/desktop' / name
    cells = doll_panels(name)
    sheet = Image.new('RGB', (sum(cell.width for cell in cells), cells[0].height + 24), (25, 25, 30))
    draw = ImageDraw.Draw(sheet)
    x = 0
    for (_, label, _), cell in zip(MEMBERS, cells):
        sheet.paste(cell, (x, 24))
        draw.text((x + 6, 5), f'{name}: {label}', fill='white')
        x += cell.width
    sheet.save(log / 'sheet.jpg', quality=92)
    print(log / 'sheet.jpg')


if __name__ == '__main__':
    main()
