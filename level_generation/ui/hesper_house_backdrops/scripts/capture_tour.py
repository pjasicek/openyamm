#!/usr/bin/env python3
"""Open and capture all fourteen backdrop kinds with the authorized minimized desktop wrapper."""
import json
from pathlib import Path
import subprocess

from PIL import Image, ImageDraw
import yaml

PROJECT = Path(__file__).resolve().parents[1]
ROOT = PROJECT.parents[2]
backdrops = json.loads((PROJECT / 'backdrops.json').read_text())
groups = {}
for backdrop in backdrops:
    assert backdrop['tour']['house'] in backdrop['houses']
    groups.setdefault(backdrop['tour']['map'], []).append(backdrop)
captures = []
commands = []
for map_file, entries in groups.items():
    name = Path(map_file).stem
    output = PROJECT / 'review/desktop' / name
    output.mkdir(parents=True, exist_ok=True)
    tour = PROJECT / 'review' / f'tour_{name}.yml'
    steps = [{'wait': 3}, {'expect': 'gameplay'}, {'console': 'time set 12:00'}]
    for entry in entries:
        steps.extend({'console': f'qbit set {bit}'} for bit in entry['tour']['qbits'])
        steps.extend([{'console': f"event {entry['tour']['event']}"}, {'wait': 2},
                      {'capture': entry['key']}, {'click': [1252, 820]}, {'wait': .5}])
        captures.append((entry['label'], output / (entry['key'] + '.png')))
    tour.write_text('# Generated by scripts/capture_tour.py; isolated review saves only.\n'
                    + yaml.safe_dump({'output_dir': str(output), 'exit': True, 'steps': steps}, sort_keys=False))
    commands.append((name, ['flock', '-s', str(ROOT / 'output/hesper_stage/locks/engine_build.lock'),
                            'flock', '-s', str(ROOT / 'output/hesper_stage/locks/stage.lock'),
                            './tools/run_game.sh', '--isolated', 'house_backdrops_' + name,
                            '--world', 'hesper', '--map', map_file,
                            '--assets', str(ROOT / 'output/hesper_stage/assets_editor_dev'),
                            '--set', 'debug.menu_input_tour_path=' + str(tour), '--warmup', '1', '--seconds', '60']))
assert len(captures) == 14 and len({path for _, path in captures}) == 14
for name, command in commands:
    print('Capturing ' + name, flush=True)
    with (PROJECT / 'review' / f'capture_{name}.log').open('w') as log:
        subprocess.run(command, cwd=ROOT, stdout=log, stderr=subprocess.STDOUT, check=True, timeout=300)
sheet = Image.new('RGB', (3 * 640, -(-len(captures) // 3) * 386), (25, 25, 30))
draw = ImageDraw.Draw(sheet)
for index, (label, path) in enumerate(captures):
    assert path.is_file(), f'Missing native capture: {path}'
    x, y = (index % 3) * 640, (index // 3) * 386
    draw.text((x + 5, y + 5), label, fill='white')
    with Image.open(path) as image:
        image.thumbnail((640, 360), Image.Resampling.LANCZOS)
        sheet.paste(image.convert('RGB'), (x, y + 24))
sheet.save(PROJECT / 'review/desktop/sheet.jpg', quality=95)
print('Captured all 14 kinds; inspect review/desktop/sheet.jpg and the five wrapper logs')
