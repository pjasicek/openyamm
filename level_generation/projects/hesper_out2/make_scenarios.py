def walk(label, start, toward, stop_short, stop_far, slide=200):
    """Walk forward four seconds from start toward a point; the party must stop between stop_short and stop_far
    along (a wall stops it; an open way lets it run about 3 000), give or take `slide` along a wall."""
    yaw = math.atan2(toward[1] - start[1], toward[0] - start[0])
    middle = (stop_short + stop_far) / 2
    stop = (start[0] + math.cos(yaw) * middle, start[1] + math.sin(yaw) * middle)
    return [{'note': label},
            {'movement_segment': {
                'input': 'forward', 'duration_ms': 4000, 'delta_game_minutes': 0.0,
                'start': pose(start[0], start[1], yaw), 'expect_stop': pose(stop[0], stop[1], yaw),
                'tolerance_xy': round(math.hypot((stop_far - stop_short) / 2, slide)), 'tolerance_z': 400,
                'loose_tolerance': True, 'actor_collision': False, 'actor_ai': False}}]


