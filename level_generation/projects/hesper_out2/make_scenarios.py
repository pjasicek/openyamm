heights = {}


def ground(x, y, map_file='hes_out2.odm'):
    """The native triangle height at a world point."""
    if map_file not in heights:
        heights[map_file] = parse_odm_file(RUNTIMES[map_file])['payload']['height_map']
    h = heights[map_file]
    fx, fy = (x + 32768.0) / 512.0, (32768.0 - y) / 512.0
    ix, iy = min(max(int(fx), 0), 126), min(max(int(fy), 0), 126)
    tx, ty = fx - ix, fy - iy
    h00, h10, h01, h11 = (h[(iy + dy) * 128 + ix + dx] * 32.0 for dy, dx in ((0, 0), (0, 1), (1, 0), (1, 1)))
    if tx + ty <= 1:
        return h00 + (h10 - h00) * tx + (h01 - h00) * ty
    return h11 + (h01 - h11) * (1 - tx) + (h10 - h11) * (1 - ty)


def pose(x, y, yaw, map_file='hes_out2.odm', z=None):
    return {'map': map_file, 'x': round(x, 1), 'y': round(y, 1),
            'z': round(ground(x, y, map_file) if z is None else z, 1), 'yaw': round(yaw, 6), 'pitch': 0.0}


def scenario(name, steps, party=None):
    flow = {'start_map': 'hes_out2.odm'}
    if party:
        flow['party'] = party
    document = {'id': f'hesper.out2.{name}', 'world': 'hesper', 'mode': 'faithful',
                'steps': [{'new_game_flow': flow}, {'assert': {'map': 'hes_out2.odm'}}] + steps}
    path = PROJECT / f'{name}.yml'
    path.write_text('# Generated by level_generation/projects/hesper_out2/make_scenarios.py from out2_build.json.\n'
                    '# Run from output/hesper_stage/scenario_run (its settings.ini mounts the stage).\n'
                    + yaml.safe_dump(document, sort_keys=False, width=120))
    print(path)


def hacker(mastery):
    """A strong party of one with the Hacking skill (1 Novice, 2 Expert)."""
    return {'members': [{'name': 'Scour tester', 'class': 'Knight', 'level': 1000, 'equipment': {},
                         'skills': [{'name': 'Hacking', 'level': 6 if mastery == 1 else 10, 'mastery': mastery}]}]}


def click(event, target, distance=360.0, map_file='hes_out2.odm', lift=120.0, standoff=None):
    """Stand `distance` from a target point (a decoration or a face) and replay a click on it: the recorded
    event-target pick that runs the map event (as the recorded MM6 routes do)."""
    tx, ty = target[:2]
    tz = (target[2] if len(target) > 2 else ground(tx, ty, map_file)) + lift
    angle = standoff if standoff is not None else math.atan2(ty - record['arrivals']['west']['position'][1],
                                                             tx - record['arrivals']['west']['position'][0])
    px, py = tx - math.cos(angle) * distance, ty - math.sin(angle) * distance
    pz = ground(px, py, map_file)
    yaw = math.atan2(ty - py, tx - px)
    dz = tz - pz
    pitch = math.asin(max(-1.0, min(1.0, dz / math.sqrt(distance * distance + dz * dz))))
    return {'press_interact': {'kind': 'event_target', 'triggered_event': event, 'hit': f'({tx},{ty},{tz})',
                               'pose': {'map': map_file, 'x': round(px, 1), 'y': round(py, 1), 'z': round(pz, 1),
                                        'yaw': round(yaw, 5), 'pitch': round(pitch, 5)}}}


def door(event):
    """Stand before an event face of the map (its recorded pose) and press it."""
    x, y, z, yaw = record['door_poses'][str(event)]
    return [{'set_pose': {'map': 'hes_out2.odm', 'x': x, 'y': y, 'z': z, 'yaw': yaw, 'pitch': 0.0}},
            {'press_interact': {}}]


def edge_trip(source_id, edge_pose, destination):
    return [{'set_pose': edge_pose},
            {'setup_shortcut': {'kind': 'map_transition_prompt', 'source_id': source_id}},
            {'assert': {'map_transition_requested': {'source_kind': 'map_boundary', 'source_id': source_id,
                                                     'destination_map': destination}}},
            {'select_topic': {'kind': 'map_transition_confirm', 'source_id': source_id, 'action_id': 0,
                              'selection_index': 0, 'label': 'OK'}},
            {'assert': {'map': destination}}]


