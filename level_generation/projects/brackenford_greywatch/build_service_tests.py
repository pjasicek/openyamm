"""Generate native house/teacher checks from scoped registrations and the ordinary test party."""
import copy
import json
import math
from pathlib import Path

import yaml

PROJECT = Path(__file__).resolve().parent
PARTY = json.loads((PROJECT / 'source/baseline_party.json').read_text())
HOUSES = json.loads((PROJECT / 'source/town_registry.json').read_text())['houses']


def start(party=PARTY):
    return {'new_game_flow': {'start_map': 'lg01.odm', 'party': party}}


def visit(house):
    x, y, z = house['door_position']
    nx, ny = house['door_outward']
    return [{'set_pose': {'map': 'lg01.odm', 'x': x+nx*192, 'y': y+ny*192, 'z': z,
                          'yaw': house['approach_yaw'], 'pitch': 0}}, {'press_interact': {}}]


def value(variable_id, expected, member=0):
    return {'assert': {'runtime_event_variable': {'id': variable_id, 'value': expected, 'member_index': member}}}


def close_teacher():
    # Escape first leaves the mastery offer, then closes the NPC conversation.
    return [{'press_action': {'action': 'escape'}}, {'press_action': {'action': 'escape'}},
            {'assert': {'dialog': {'active': False}}}]


def write(name, title, steps):
    scenario = {'id': 'levelgen.brackenford.' + name, 'title': title,
                'world': 'mm8', 'mode': 'faithful', 'steps': steps}
    (PROJECT / (name + '.yml')).write_text('# Generated by build_service_tests.py.\n'
                                         + yaml.safe_dump(scenario, sort_keys=False))


doors = [start()]
for house in HOUSES:
    npc = house['npc']
    expected = {'active': True, 'house_dialog': not bool(npc),
                'source_id': npc['instance_id'] if npc else house['house_id']}
    expected['title' if npc else 'house_title'] = npc['name'] if npc else house['house_name']
    doors += visit(house) + [{'assert': {'dialog': expected}}, {'press_action': {'action': 'escape'}}]
write('town_doors', 'All 24 native house doors open their scoped MM8 services or residents', doors)

# Joined legacy skill values: Expert level7 = 64+7; Master level7 = 128+7.
# Fees follow the existing shared MM8 mastery rules: Sword5000, Water4000, utilities2500.
teachers = [('teacher_1', 0, 69, 5000, 1), ('teacher_2', 4, 82, 4000, 0),
            ('teacher_3', 2, 97, 2500, 0), ('teacher_4', 2, 94, 2500, 0)]
positive = [start()]
gold = PARTY['gold']
for building, member, skill_variable, fee, wrong_member in teachers:
    house = next(h for h in HOUSES if h['building'] == building)
    topic = house['npc']['topics'][0]['id']
    gold -= fee
    positive += visit(house) + [
        {'press_action': {'action': 'select_member', 'member_index': member}},
        value(skill_variable, 71, member), {'select_topic': {'action_id': topic}},
        {'select_topic': {'action_id': topic}}, value(skill_variable, 135, member), value(21, gold),
        {'select_topic': {'action_id': topic}}, value(skill_variable, 135, member), value(21, gold)]
    positive += close_teacher()
positive += [{'save_game': 'brackenford_teachers_learned'}, {'load_game': 'brackenford_teachers_learned'}]
positive += [value(skill_variable, 135, member) for _, member, skill_variable, _, _ in teachers]
positive.append(value(21, gold))
write('town_teacher_learning', 'Four MM8 teachers charge once, improve eligible skills and preserve saved mastery', positive)

negative = [start()]
for building, member, skill_variable, _, wrong_member in teachers:
    house = next(h for h in HOUSES if h['building'] == building)
    topic = house['npc']['topics'][0]['id']
    negative += visit(house) + [
        {'press_action': {'action': 'select_member', 'member_index': wrong_member}},
        {'select_topic': {'action_id': topic}}, {'select_topic': {'action_id': topic}},
        value(skill_variable, 71, member), value(21, PARTY['gold'])]
    negative += close_teacher()
write('town_teacher_eligibility', 'Ineligible students cannot buy mastery or lose gold at any of the four teachers', negative)

# Supply normal earned experience as fixture setup; actual level-up, payment and time advance use the house action.
training_party = copy.deepcopy(PARTY)
training_party['members'][0]['experience'] = 325000
training_house = next(h for h in HOUSES if h['building'] == 'training')
training = [start(training_party)] + visit(training_house) + [
    {'press_action': {'action': 'select_member', 'member_index': 0}},
    value(9, 25), value(13, 325000),
    {'assert': {'dialog': {'house_title': "Assassin's School", 'actions': [
        {'index': 0, 'id': 5, 'enabled': True, 'label': 'Train to level 26 for 637 gold'}, {'index': 1, 'id': 8, 'enabled': True}]}}},
    {'select_topic': {'action_id': 5}}, value(9, 26), value(13, 325000), value(21, 49363),
    {'assert': {'dialog': {'actions': [{'index': 0, 'id': 5, 'enabled': False}, {'index': 1, 'id': 8, 'enabled': True}]}}},
    {'press_action': {'action': 'escape'}},
    {'save_game': 'brackenford_training'}, {'load_game': 'brackenford_training'},
    value(9, 26), value(21, 49363),
    start()] + visit(training_house) + [
    {'press_action': {'action': 'select_member', 'member_index': 0}},
    {'assert': {'dialog': {'actions': [{'index': 0, 'id': 5, 'enabled': False}, {'index': 1, 'id': 8, 'enabled': True}]}}},
    value(9, 25), value(21, 50000), {'press_action': {'action': 'escape'}}]
write('town_training', 'Existing MM8 high-level training profile advances eligible members and preserves saved level', training)
