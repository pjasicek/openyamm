"""Generate faithful fixture, combat observation and new door-control scenarios from the canonical party.

Combat observations exercise ordinary input; final difficulty tuning belongs to the driver.
No scenario generated here disables actor AI, actor collision or party damage.
"""
import copy
import json
import math
from pathlib import Path

import yaml

PROJECT = Path(__file__).resolve().parent
PARTY = json.loads((PROJECT / 'source/baseline_party.json').read_text())


def start():
    return {'new_game_flow': {'start_map': 'lg02.blv', 'party': copy.deepcopy(PARTY)}}


def pose(x, y, z=384, yaw=0):
    return {'map': 'lg02.blv', 'x': x, 'y': y, 'z': z, 'yaw': yaw, 'pitch': 0}


def variable(member, variable_id, **expectation):
    return {'assert': {'runtime_event_variable': dict(id=variable_id, member_index=member, **expectation)}}


def write(name, title, steps):
    content = {'id': 'levelgen.' + name, 'title': title, 'world': 'mm8', 'mode': 'faithful', 'steps': steps}
    (PROJECT / (name + '.yml')).write_text(
        '# Generated by build_baseline_tests.py; party source is source/baseline_party.json.\n'
        + yaml.safe_dump(content, sort_keys=False))


equipment = [{'member_index': i, 'slot': slot, 'item_id': item_id}
             for i, member in enumerate(PARTY['members']) for slot, item_id in member['equipment'].items()]
smoke = [start(), {'assert': {'equipped_item': equipment}},
         {'save_game': 'levelgen_baseline_party'}, {'load_game': 'levelgen_baseline_party'},
         {'assert': {'equipped_item': equipment}}]
for i, maximum in enumerate([260, 90, 115, 214, 80]):
    smoke += [variable(i, 9, value=25), variable(i, 3, min=maximum, max=maximum)]
write('baseline_party_smoke', 'Fresh ordinary level25 MM8 party, equipment and resources persist', smoke)

entrance = [start(), {'set_pose': pose(-128, 1056, 768, math.pi / 2)}, {'press_interact': {}},
            {'wait_until': {'timeout_runtime_seconds': 2.5, 'assert': {'mechanism': {'id': 1, 'state': 'open'}}}},
            {'assert_mechanism': {'id': 2, 'state': 'open'}},
            {'set_pose': pose(0, 1120, 768, math.pi / 2)},
            {'press_action': {'action': 'attack', 'seconds': 45}},
            variable(0, 13, min=300001)]
for i in range(20, 24):
    entrance.append({'assert': {'actor_visible': {'actor_index': i, 'report_state': True}}})
for i in range(5):
    # Report a physical resource range, without claiming a particular survival rate proves final balance.
    entrance.append(variable(i, 3, min=-1000, max=[260, 90, 115, 214, 80][i]))
write('greywatch_entrance_combat', 'Ordinary shared attack input earns experience; observe entrance fight', entrance)

records = [start(), {'set_pose': pose(5632, 3968, yaw=-1.85)},
           {'press_action': {'action': 'attack', 'seconds': 30}}, variable(0, 13, min=300001)]
for i in range(2, 15):
    records.append({'assert': {'actor_visible': {'actor_index': i, 'report_state': True}}})
for i in range(5):
    records.append(variable(i, 3, min=-1000, max=[260, 90, 115, 214, 80][i]))
write('greywatch_records_combat', 'Records fight observation with closed side doors; driver tunes final balance', records)


def control(steps, position, door, state):
    steps += [{'set_pose': position}, {'press_interact': {}},
              {'wait_until': {'timeout_runtime_seconds': 4.25,
                              'assert': {'mechanism': {'id': door, 'state': state}}}}]


doors = [start(), {'assert_mechanism': {'id': 7, 'state': 'closed'}},
         {'assert_mechanism': {'id': 8, 'state': 'closed'}},
         {'movement_segment': {'start': pose(5632, 2400, yaw=-math.pi / 2),
                               'expect_stop': pose(5632, 2157, yaw=-math.pi / 2),
                               'seconds': 0.5, 'input': 'forward'}}]
control(doors, pose(6016, 2240, yaw=-math.pi / 2), 7, 'open')
doors += [{'save_game': 'greywatch_records_south_open'}, {'load_game': 'greywatch_records_south_open'},
          {'assert_mechanism': {'id': 7, 'state': 'open'}}]
control(doors, pose(5552, 1952, 352, math.pi), 7, 'closed')
# Fresh party keeps the second control test independent of the first encounter's damage and pursuit.
doors += [start(), {'movement_segment': {'start': pose(6752, 3072), 'expect_stop': pose(6939, 3072),
                                       'seconds': 0.5, 'input': 'forward'}}]
control(doors, pose(6848, 3008, yaw=-math.pi / 2), 8, 'open')
doors += [{'save_game': 'greywatch_barracks_open'}, {'load_game': 'greywatch_barracks_open'},
          {'assert_mechanism': {'id': 8, 'state': 'open'}}]
control(doors, pose(7168, 3008, yaw=-math.pi / 2), 8, 'closed')
write('greywatch_encounter_doors', 'Closed world collision, controls on both sides and saved native door state', doors)
