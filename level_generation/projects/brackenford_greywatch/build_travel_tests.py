"""Author real map-edge walking and stable purchase/return checks; no direct event dispatch."""
import json
import math
from pathlib import Path
import yaml

PROJECT=Path(__file__).resolve().parent
party=json.loads((PROJECT/'source/baseline_party.json').read_text())

def pose(map_name,x,y,z,yaw):return dict(map=map_name,x=x,y=y,z=z,yaw=yaw,pitch=0)
def start():return {'new_game_flow':dict(start_map='lg01.odm',party=party)}
def confirm():return {'select_topic':dict(action_id=0,kind='map_transition_confirm')}
def choose(label):return {'select_topic':dict(action_id=22,match_label=label)}
def map_check(name):return {'assert':{'map':name}}
def gold(value):return {'assert':{'runtime_event_variable':dict(id=21,value=value,member_index=0)}}
def write(name,steps,title):
 (PROJECT/(name+'.yml')).write_text('# Generated by build_travel_tests.py.\n'+yaml.safe_dump(dict(
  id='levelgen.brackenford.'+name,title=title,world='mm8',mode='faithful',steps=steps),sort_keys=False))

steps=[]
for edge,destination,days,a,b,fee in [
 ('west','out02.odm',1,pose('lg01.odm',-24448,-1536,576,math.pi),pose('lg01.odm',-24539,-1536,576,math.pi),42),
 ('north','out03.odm',2,pose('lg01.odm',-18432,24448,960,math.pi/2),pose('lg01.odm',-18432,24539,960,math.pi/2),63)]:
 steps += [start(),{'movement_segment':dict(start=a,expect_stop=b,seconds=.25,input='forward')},
  {'assert':{'map_transition_requested':dict(destination_map=destination,pos='(16960,-12512,0)' if edge=='west' else '(4040,13184,288)')}},confirm(),map_check(destination),
  {'assert':{'runtime_event_variable':dict(id=23,value=35,member_index=0)}},
  {'press_interact':{}},{'assert':{'dialog':dict(active=True,house_title='Guild Caravans')}},
  choose('1 day to Brackenford for '+str(fee)+' gold'),map_check('lg01.odm'),gold(50000-fee),
  {'save_game':'brackenford_'+edge+'_return'},{'load_game':'brackenford_'+edge+'_return'},map_check('lg01.odm')]
write('regional_travel',steps,'Walk both native boundary roads, confirm travel, use existing stable return and reload')

stable=next(h for h in json.loads((PROJECT/'source/town_registry.json').read_text())['houses'] if h['building']=='stables')
x,y,z=stable['door_position'];nx,ny=stable['door_outward']
steps=[start(),{'set_pose':pose('lg01.odm',x+nx*192,y+ny*192,z,stable['approach_yaw'])},
 {'press_interact':{}},{'assert':{'dialog':dict(active=True,house_title='Guild Caravans',actions=[
  dict(index=0,id=22,enabled=True,label='2 days to Alvar for 42 gold')])}},
 choose('2 days to Alvar for 42 gold'),map_check('out03.odm'),gold(49958),
 {'set_pose':pose('out03.odm',4040,13184,288,math.pi/2)},{'press_interact':{}},
 choose('1 day to Brackenford for 63 gold'),map_check('lg01.odm'),gold(49895),
 {'save_game':'brackenford_stables_roundtrip'},{'load_game':'brackenford_stables_roundtrip'},map_check('lg01.odm'),gold(49895)]
write('stables_travel',steps,'Original MM8 scheduled stable route, actual fares, daily return and save/load')
