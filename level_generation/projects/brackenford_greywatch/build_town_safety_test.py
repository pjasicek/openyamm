"""Generate a >5-minute active-AI town check, including a continuous walk around the occupied perimeter.

Service positions are explicit scenario setups, not a claim of continuous travel between every house.
The perimeter legs are contiguous native movement with normal actor/world collision.
"""
import json
import math
from pathlib import Path

import yaml

from build_outdoor_content import terrain_height

PROJECT = Path(__file__).resolve().parent
party = json.loads((PROJECT / 'source/baseline_party.json').read_text())
houses = json.loads((PROJECT / 'source/town_registry.json').read_text())['houses']
actors = json.loads((PROJECT / 'source/lg01.content.json').read_text())['actors']
heights = bytes.fromhex(json.loads((PROJECT / 'source/lg01.terrain.yml').read_text())['height_map_hex'])
steps = [{'new_game_flow': {'start_map': 'lg01.odm', 'party': party}}]
elapsed = 0.0


def population_check():
    result = []
    for actor in actors:
        expected = {'actor_index': actor['actor_index'], 'dead': False, 'current_hp': actor['hp'],
                    'hostile_to_party': actor['actor_index'] >= 29,
                    'has_detected_party': False, 'combat_targeting_party': False}
        result.append({'assert': {'actor_visible': expected}})
    return result


def pose(x, y, yaw):
    return {'map': 'lg01.odm', 'x': x, 'y': y, 'z': terrain_height(x, y, heights), 'yaw': yaw, 'pitch': 0}


corners = [(-20480, -10240), (0, -10240), (0, 9216), (-20480, 9216), (-20480, -10240)]
for (x0, y0), (x1, y1) in zip(corners, corners[1:]):
    yaw = math.atan2(y1-y0, x1-x0)
    duration = math.hypot(x1-x0, y1-y0) / 768
    steps.append({'movement_segment': {'start': pose(x0, y0, yaw), 'expect_stop': pose(x1, y1, yaw),
                                       'seconds': duration, 'input': 'forward'}})
    elapsed += duration
    steps += population_check()

for house in houses:
    x, y, z = house['door_position']
    nx, ny = house['door_outward']
    steps += [{'set_pose': dict(pose(x+nx*192, y+ny*192, house['approach_yaw']), z=z)},
              {'advance_runtime': {'seconds': 10}}]
    elapsed += 10
    steps += population_check()
    steps += [{'press_interact': {}}, {'assert': {'dialog': {'active': True}}},
              {'press_action': {'action': 'escape'}}, {'assert': {'dialog': {'active': False}}}]
for i, hp in enumerate([260, 90, 115, 214, 80]):
    steps.append({'assert': {'runtime_event_variable': {'id': 3, 'member_index': i, 'value': hp}}})
assert elapsed >= 300
scenario = {'id': 'levelgen.brackenford.town_safety', 'title': 'Ordinary party walks town perimeter and visits all doors with active AI',
            'world': 'mm8', 'mode': 'faithful', 'steps': steps}
(PROJECT / 'town_safety.yml').write_text('# Generated by build_town_safety_test.py.\n' + yaml.safe_dump(scenario, sort_keys=False))
(PROJECT / 'source/town_safety_plan.json').write_text(json.dumps({
    'perimeter_corners': corners, 'nominal_world_seconds': elapsed, 'house_visits': len(houses),
    'standing_world_seconds_per_house': 10, 'actor_count': len(actors),
    'limits': 'Contiguous perimeter walking; explicit setup at service approaches. No exhaustive movement path between houses.'}, indent=2) + '\n')
print('Generated town safety check: %.3f world seconds, %d steps' % (elapsed, len(steps)))
