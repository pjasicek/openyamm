"""Focused pursuit fights and desktop review poses for the walkability revision."""
import json
import math
from pathlib import Path

import yaml

PROJECT = Path(__file__).resolve().parent
CASES = [
    ('west_root_stair', (2964, 2500, -768), (2964, 620, 0)),
    ('east_root_stair', (4636, 2500, -768), (4636, 620, 0)),
    ('pond_root_stair', (3800, 3200, -1536), (3800, 1180, -768)),
    ('royal_stair', (300, -100, -2944), (300, 2800, -1536)),
    ('pond_southwest', (3450, 1700, -1568), (2800, 2600, -1536)),
    ('pond_southeast', (4700, 1700, -1568), (5400, 2700, -1536)),
    ('pond_northwest', (3450, 2650, -1568), (2800, 1200, -1536)),
    ('pond_northeast', (4700, 2650, -1568), (5400, 1200, -1536)),
    ('mother_west_pool', (3150, 100, -2976), (3800, 900, -2944)),
    ('mother_east_pool', (5500, 100, -2976), (4800, 900, -2944)),
    ('sump_escape_ramp', (6030, 1100, -1736), (6860, 1100, -1536)),
    ('cistern_west', (7360, 900, -1568), (8200, 1700, -1536)),
    ('cistern_middle', (7680, 900, -1568), (8200, 1700, -1536)),
    ('cistern_east', (8000, 900, -1568), (7200, 1700, -1536)),
    ('spawning_pool', (6200, 3336, -1568), (6200, 2400, -1536)),
    ('birth_pit_west', (3100, 3930, -3200), (3100, 3150, -2944)),
    ('birth_pit_middle', (4100, 3930, -3200), (4100, 3150, -2944)),
    ('birth_pit_east', (5100, 3930, -3200), (5100, 3150, -2944)),
    ('creche_bones', (3780, 5400, 0), (3780, 4700, 0)),
    ('larder_bones', (1710, 1570, -768), (2250, 900, -768)),
    ('throat_bones', (800, 500, -2944), (800, -400, -2944)),
    ('vat_keeper_lane', (6300, 3000, 0), (6300, 3800, 0)),
    ('west_underpass', (2964, 1500, -768), (4100, 1250, -768)),
    ('east_underpass', (4636, 1500, -768), (3500, 1250, -768)),
]
scene = json.loads((PROJECT / 'runtime/hes_d09.scene.yml').read_text())
actors = scene['initial_state']['actors']
shield_rows = [line.split('\t') for line in
               (PROJECT.parents[2] / 'design/kreegan_world/data/monster_hesper.txt').read_text().splitlines()]
shielded = {int(row[0]) for row in shield_rows if row[0].isdigit() and int(row[2]) > 0}
assert len(actors) == 96
steps = []
shots = []
for name, spawn, party in CASES:
    assert math.dist(spawn[:2], party[:2]) > 400, name
    steps += [{'note': {'text': name}}, {'new_game_flow': {'start_map': 'hes_d09.blv', 'party': {'members': [
        {'name': 'Brood tester', 'class': 'Knight', 'level': 1000, 'equipment': {},
         'skills': [{'name': 'Sword', 'level': 1, 'mastery': 1}]}]}}}]
    # Clear nearby packs, preserving the Mother and her sacs so death hooks do not open message boxes mid-fight.
    for actor in actors:
        if 77 <= actor['actor_index'] <= 92:
            continue
        pos = tuple(actor['position'][k] for k in ('x', 'y', 'z'))
        if min(math.dist(pos, spawn), math.dist(pos, party)) < 2600:
            hit = {'damage_actor': {'actor_index': actor['actor_index'], 'amount': 1000000, 'tier': 'kreegan_energy'}}
            steps += [hit.copy() for _ in range(2 if actor['monster_id'] in shielded else 1)]
    yaw = math.atan2(spawn[1] - party[1], spawn[0] - party[0])
    steps += [{'set_pose': dict(map='hes_d09.blv', x=party[0], y=party[1], z=party[2], yaw=yaw, pitch=0)},
              {'spawn_actor': dict(monster_id=10000, count=1, x=spawn[0], y=spawn[1], z=spawn[2])},
              # Wake the test defender so this measures pursuit across the floor.
              {'damage_actor': {'actor_index': 96, 'amount': 1, 'tier': 'physical'}},
              {'advance_runtime': {'seconds': 30}},
              {'assert': {'actor_visible': {'actor_index': 96, 'report_state': True, 'dead': False,
                                           'near': {'x': party[0], 'y': party[1], 'max_distance': 400}}}}]
    shots.append(dict(name=name, position=list(party), yaw=round(yaw, 4), pitch=-0.12))
shots += [dict(name=name, position=pos, yaw=yaw, pitch=0.22) for name, pos, yaw in (
    ('molt_octagon_and_hip', [300, 1550, 0], 1.57), ('chamfered_descent', [7400, 1800, 0], 3.14),
    ('hatched_niche', [2900, 4700, 0], 1.57), ('royal_gallery_hip', [1600, 1050, -2944], 1.57),
    ('mother_chamber_and_cradle_supports', [4300, 1200, -2944], 1.57))]
(PROJECT / 'd09_walkability.yml').write_text('# Generated by make_walkability.py; 400-unit pursuit checks at every fixed spot.\n' +
    yaml.safe_dump(dict(id='hesper.d09.walkability', world='hesper', mode='faithful', steps=steps), sort_keys=False))
(PROJECT / 'review_tour_walkability.yml').write_text(yaml.safe_dump(dict(
    output_dir=str(PROJECT / 'review/walkability/capture'), settle_seconds=1.5, exit=True, shots=shots), sort_keys=False))
print(f'{len(CASES)} pursuit fights; {len(shots)} desktop poses')
