"""Write `hostile_spawns.yml`, the headless check of Starport Reach's hostile monsters, from the built scene and
`work/spawns_plan.json` (spawns.py): on load the spawn points' drones and Glassbacks, the Hunters, the Bull, the
Troopers and the Ashrunners are hostile and stand where they were placed, Landfall's people stay friendly; with S1's
QBit set the Ashrunners are friendly once the game is saved and loaded again.

    python3 level_generation/projects/hesper_out1/make_spawns_scenario.py
    cd output/hesper_stage/scenario_run && ../../../build/game/openyamm --headless-run-scenario \
        ../../../level_generation/projects/hesper_out1/hostile_spawns.yml
"""
import json
from pathlib import Path

import yaml

PROJECT = Path(__file__).resolve().parent
scene = json.loads((PROJECT / 'source/hes_out1.scene.yml').read_text())
plan = json.loads((PROJECT / 'work/spawns_plan.json').read_text())
actors = scene['initial_state']['actors']


def placed(monster):
    """The first placed actor of a monster row (the squads are spawns.py's)."""
    return next(a for a in actors if a['monster_id'] == monster and a['group'] >= 30)


steps = [{'load_map': {'map': 'hes_out1.odm'}},
         {'set_pose': {'map': 'hes_out1.odm', 'x': -14400, 'y': -16000, 'z': 1600, 'yaw': 0.0, 'pitch': 0}},
         {'advance_runtime': {'seconds': 1}},
         {'note': {'text': 'Placed squads: hostile, at their spots.'}}]
for monster, label in [(10010, 'Trooper'), (10070, 'Ashrunner Scav'), (10072, 'Ashrunner Gunner'),
                       (10051, 'Hunter Drone'), (10082, 'Glassback Bull')]:
    a = placed(monster)
    steps.append({'assert': {'actor_visible': {
        'actor_index': a['actor_index'], 'monster_id': monster, 'report_state': True, 'hostile_to_party': True,
        'near': {'x': a['position']['x'], 'y': a['position']['y'], 'max_distance': 400}}}})
# The spawned actors follow the placed ones, spawn point by spawn point: the first is the first point's.
first_spawn = plan['spawns'][0]
steps.append({'note': {'text': 'Encounter spawns: the first drone of the first spawn point, hostile, by its point.'}})
steps.append({'assert': {'actor_visible': {
    'actor_index': len(actors), 'report_state': True, 'hostile_to_party': True,
    'near': {'x': first_spawn['position'][0], 'y': first_spawn['position'][1], 'max_distance': 600}}}})
steps.append({'note': {'text': "Landfall's people stay friendly (a guard and a villager)."}})
guard = next(a for a in actors if a['monster_id'] == 10067)
villager = next(a for a in actors if a['monster_id'] in (10073, 10076))
for a in (guard, villager):
    steps.append({'assert': {'actor_visible': {'actor_index': a['actor_index'], 'hostile_to_party': False}}})
steps.append({'note': {'text': 'With S1 done (its QBit) the Ashrunners are friendly on the next load.'}})
steps.append({'setup_shortcut': {'kind': 'set_qbit', 'id': 100101, 'reason': 'S1 done'}})
steps.append({'save_game': 'hesper_s1'})                 # a load (not a second load_map: that starts a new game)
steps.append({'load_game': 'hesper_s1'})
steps.append({'advance_runtime': {'seconds': 1}})
a = placed(10070)
steps.append({'assert': {'actor_visible': {'actor_index': a['actor_index'], 'report_state': True,
                                           'hostile_to_party': False}}})
scenario = {'id': 'hesper.out1.hostile_spawns', 'world': 'hesper', 'mode': 'faithful', 'steps': steps}
header = ('# Generated by make_spawns_scenario.py from the built scene and work/spawns_plan.json (README, "Hostile '
          'monsters").\n# Run from output/hesper_stage/scenario_run (its settings.ini mounts the stage).\n')
(PROJECT / 'hostile_spawns.yml').write_text(header + yaml.safe_dump(scenario, sort_keys=False, width=120))
print(f'{len(steps)} steps')
