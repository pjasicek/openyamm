"""The great ion cannon's effects (design/kreegan_world/COMBAT.md "Ion cannons", "The look and the shot"), built with
the engine effect generator's layer helpers (tools/fx/generate_projectile_effects.py), as the stage's projectile
effects are. build_out4.py writes them into runtime/worlds/hesper/effects/hes_out4.yml (the stage imports a map's
effect library); the cannon timer (event 3) draws and spawns them (evt.BeamToParty, evt.SpawnWorldEffect):

  hesper:fx/beam/crown_lock            the red lock beam from the muzzle to the party (evt.BeamToParty, renewed as
                                the head turns), for the lock's seconds
  hesper:fx/impact/crown_muzzle        the muzzle flash on release

The ion pulse and its blast are the CrownIon missile's flight and impact (hesper_stage/projectiles.yml and
projectile_effects.py: crown_ion), fired with evt.FireMissile.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'tools/fx'))
import generate_projectile_effects as fx  # noqa: E402
from generate_projectile_effects import fade, flash, impact, scales  # noqa: E402

VIOLET = (170, 110, 255)
WHITE_VIOLET = (235, 220, 255)


def lock_beam(index, texture, width, rgb, transparency, fill, core):
    """One ribbon of a beam effect (beam: true), running from the effect to its beam target for its whole life. Its
    width keys run along the beam: it tapers to a thread at the party, where the viewer's eye is."""
    return {'id': index, 'type': 'ribbon', 'start_seconds': 0, 'end_seconds': 600,
            'sprite_resource': fx.SPRITE + texture, 'blend': 'additive', 'beam': True, 'lifetime_seconds': 1,
            'width': width, 'sample_distance': 64, 'texture_length': 600, 'scroll_speed': 4, 'fill': fill,
            'core': core,
            'width_keys': [{'time': 0, 'value': 1}, {'time': 0.85, 'value': 0.5}, {'time': 1, 'value': 0.04}],
            'color_keys': [{'time': 0, 'rgb': rgb, 'transparency': transparency}]}


def effects():
    return [
        {'id': 'openyamm:fx/beam/crown_lock', 'display_name': 'Ion cannon lock beam',
         'comment': 'The great cannon\'s lock: a red beam from the muzzle to the party, a white core in a red sheath.',
         'duration_seconds': 600, 'compatibility_profile': 'predictable',
         'components': [lock_beam(1, 'trail_noise', 90, [255, 40, 30], 30, fill=0.7, core=0.6),
                        lock_beam(2, 'trail_noise', 26, [255, 210, 200], 0, fill=1.0, core=1.0)]},
        impact('crown_muzzle', 'Ion cannon muzzle flash',
               'The release: a white star at the muzzle crown with violet rays.', 0.6,
               [flash('glow', 0, 0.45, scales(6.0, 12.0), fade(WHITE_VIOLET)),
                flash('flare_star', 0, 0.4, scales(6.0, 11.0), fade((255, 250, 255))),
                flash('rays', 0, 0.35, scales(5.0, 10.0), fade(VIOLET))]),
    ]


def write(path):
    """Write the effect library (Hesper ids) and return the ids."""
    items = effects()
    for item in items:
        item['id'] = item['id'].replace('openyamm:fx/', 'hesper:fx/', 1)
    lines = ['# Generated by level_generation/projects/hesper_out4/crown_effects.py (build_out4.py).',
             'schema: openyamm.effectLibrary.v1', 'effects:']
    for item in items:
        item = dict(item)
        lines.append('# ' + item.pop('comment')[:114])
        body = fx.yaml.dump([item], Dumper=fx.Dumper, sort_keys=False, width=118, allow_unicode=True)
        lines.extend(body.rstrip('\n').split('\n'))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines) + '\n')
    return [item['id'] for item in items]
