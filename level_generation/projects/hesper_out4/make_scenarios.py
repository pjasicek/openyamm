def pose(event, map_file=MAP):
    x, y, z, yaw = build['door_poses'][str(event)]
    return {'map': map_file, 'x': x, 'y': y, 'z': z, 'yaw': yaw, 'pitch': 0.0}


def exit_pose(project, map_file, event, arrival):
    """Where to stand to click a dungeon's exit face (its event): 200 in front of the face, on the arrival's side,
    at the arrival's floor, facing it."""
    native = parse_blv_file(ROOT / 'level_generation/projects' / project / 'runtime/worlds/hesper/maps' / map_file)
    native = native['payload']
    semantic = json.loads((ROOT / 'level_generation/projects' / project / 'source' /
                           (Path(map_file).stem + '.semantic.json')).read_text())
    a = semantic['arrivals'][arrival]
    ax, ay, az = a['position']
    for face in native['faces']:
        if face['face_param']['cog_triggered'] != event:
            continue
        points = [native['vertices'][i] for i in face['vertex_indices']]
        cx = sum(p['x'] for p in points) / len(points)
        cy = sum(p['y'] for p in points) / len(points)
        (x0, y0), (x1, y1) = (points[0]['x'], points[0]['y']), (points[1]['x'], points[1]['y'])
        if math.hypot(x1 - x0, y1 - y0) < 1:
            (x1, y1) = (points[2]['x'], points[2]['y'])
        nx, ny = y1 - y0, -(x1 - x0)
        length = math.hypot(nx, ny)
        nx, ny = nx / length, ny / length
        if (ax - cx) * nx + (ay - cy) * ny < 0:
            nx, ny = -nx, -ny
        px, py = cx + nx * 200, cy + ny * 200
        return {'map': map_file, 'x': round(px), 'y': round(py), 'z': az, 'yaw': round(math.atan2(-ny, -nx), 4),
                'pitch': 0.0}
    raise SystemExit(f'{map_file}: no face of event {event}')


def stays(event, text):
    return [{'note': {'text': text}}, {'set_pose': pose(event)},
            {'press_interact': {'expect': {'kind': 'event_target'}}}, {'assert': {'map': MAP}}]


def enters(event, map_file, text):
    return [{'note': {'text': text}}, {'set_pose': pose(event)}, {'press_interact': {}}, {'assert': {'map': map_file}}]


def returns(project, map_file, event, arrival, text, door=None):
    """Out through a dungeon's exit face; `door` first opens the dungeon's own door in front of it (D12's gate
    leaves, its event 72)."""
    opening = [] if door is None else [
        {'press_interact': {}},
        {'wait_until': {'timeout_runtime_seconds': 4, 'assert': {'mechanism': {'kind': 'indoor_door', 'id': door,
                                                                               'state': 'open'}}}}]
    return [{'note': {'text': text}}, {'set_pose': exit_pose(project, map_file, event, arrival)}] + opening + [
            {'press_interact': {}},
            {'select_topic': {'kind': 'map_transition_confirm', 'source_id': 0, 'action_id': 0, 'secondary_id': 0,
                              'selection_index': 0, 'house_dialog': False, 'enabled': True, 'label': 'OK'}},
            {'assert': {'map': MAP}}]


def write(name, steps, comment):
    scenario = {'id': f'hesper.out4.{name}', 'world': 'hesper', 'mode': 'faithful',
                'steps': [{'new_game_flow': {'start_map': MAP, 'party': PARTY}}, {'assert': {'map': MAP}}] + steps}
    (PROJECT / f'{name}.yml').write_text(HEADER + ''.join(f'# {line}\n' for line in comment.split('\n'))
                                         + yaml.safe_dump(scenario, sort_keys=False, width=120))
    print(PROJECT / f'{name}.yml')


def qbit(n, value=True):
    return {'setup_shortcut': {'kind': 'set_qbit', 'id': n, 'value': value, 'reason': 'the scenario sets it'}}


