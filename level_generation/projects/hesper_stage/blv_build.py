"""The shared second half of a Hesper indoor map's build (after its Blender author script, blv_kit.py): compile the
BLV with mm9_compile_indoor_source, check every event face and light arrived, write the scene (party start, doors,
chests) and the Lua (the door table, the authored handlers with their placeholders filled, the registrations), and
copy them into the project's runtime/worlds/hesper tree for the Hesper stage.
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]


def check_fixtures():
    """The plan's light fixtures carry the radius and colour of their stage bindings (decorations.yml)."""
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        'plans', ROOT / 'design/kreegan_world/zone1/dungeons/make_dungeon_plans.py')
    plans = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(plans)
    bound = {d['name']: d.get('light') for d in
             yaml.safe_load((Path(__file__).parent / 'decorations.yml').read_text())['decorations']}
    for name, (radius, colour) in plans.FIXTURES.items():
        if name not in bound:            # zones 2-4's kit fixtures (R1): bound once their models are staged
            continue
        assert bound.get(name) == [radius, *colour], (name, bound.get(name), radius, colour)
        if name + '_off' in bound:
            assert bound[name + '_off'] is None, name + '_off'


def build(project, map_file, placeholders, arrival, chests=(), actors=()):
    """actors: the scene's placed monsters (IndoorSceneYml actor records), if the map has any. chests: in container
    order, a name (random H1) or {'name', 'fixed': [item ids], 'random': bool, 'gold': n} (fixed items first, then
    the random roll if `random`)."""
    check_fixtures()
    project = Path(project)
    stem = Path(map_file).stem
    source, runtime = project / 'source', project / 'runtime'
    runtime.mkdir(exist_ok=True)
    subprocess.run([str(ROOT / 'build/tools/mm9_compile_indoor_source'), str(source / f'{stem}.glb'),
                    str(source / f'{stem}.geometry.yml'), str(runtime / map_file), str(source / f'{stem}.doors.yml'),
                    str(source / f'{stem}.faces.yml')], check=True)
    metadata = json.loads((source / f'{stem}.geometry.yml').read_text())
    semantic = json.loads((source / f'{stem}.semantic.json').read_text())
    doors = yaml.safe_load((source / f'{stem}.doors.yml').read_text()) or []
    sys.path.insert(0, str(ROOT / 'util'))
    from map_export import parse_blv_file
    native = parse_blv_file(runtime / map_file)['payload']
    bound = {f['face_param']['cog_triggered'] for f in native['faces'] if f['face_param']['cog_triggered']}
    entity_events = {e['event_id_secondary'] for e in metadata['entities'] if e['event_id_secondary']}
    expected = {int(e) for e in semantic['events']} - entity_events
    assert expected <= bound, (sorted(expected - bound))
    assert len(native['lights']) == len(metadata['lights'])
    assert len(native['entities']) == len(metadata['entities'])
    assert {d['door_id'] for d in doors} == set(semantic['door_ids'].values()), (doors, semantic['door_ids'])

    template = ROOT / 'level_generation/projects/brackenford_greywatch/calibration/calibration.scene.yml'
    scene = json.loads(template.read_text())
    scene['source']['geometry_file'] = map_file
    scene['environment']['ceiling'] = 1024
    start = semantic['arrivals'][arrival]
    scene['party_start_points'] = [{'start_index': 0, 'source_name': 'StartPoint0', 'position': start['position'],
                                    'direction_degrees': start['direction_degrees']}]
    scene['initial_state']['doors'] = doors
    scene['initial_state']['actors'] = list(actors)
    scene['loot_containers'] = []
    for index, chest in enumerate(chests):
        chest = {'name': chest} if isinstance(chest, str) else chest
        fixed = [{'slot': slot, 'raw_mm9_item_id': 0, 'item_id': item}
                 for slot, item in enumerate(chest.get('fixed', []), 1)]
        scene['loot_containers'].append({
            'source_id': f'hesper:{stem}:chest_{index}', 'source_object_index': index, 'source_name': chest['name'],
            'position': {'x': 0, 'y': 0, 'z': 0}, 'container_id': index, 'kind': 'chest',
            'presentation': 'colonial locker', 'random_treasure_level': 1, 'treasure_type': 0,
            'gold': chest.get('gold', 60), 'gold_only': False, 'random': chest.get('random', True), 'ai_drop': False,
            'trap_level': 0, 'should_repopulate': False, 'fixed_items': fixed, 'remove_when_empty': False})
    (runtime / f'{stem}.scene.yml').write_text(json.dumps(scene, indent=2) + '\n')

    events = {int(k): v for k, v in semantic['events'].items()}
    events[1] = 'map_load'
    text = f'-- Generated by {project.name}/build; author source/{stem}.handlers.lua and the Blender source instead.\n'
    text += 'local DOORS = {' + ', '.join(f'{n} = {d}' for n, d in semantic['door_ids'].items()) + '}\n'
    chest_ids = ', '.join(f'[{e}] = {{{c}}}' for e, c in semantic.get('chest_events', {}).items())
    text += f'SetMapMetadata({{onLoad = {{1}}, onLeave = {{}}, openedChestIds = {{{chest_ids}}}}})\n'
    handlers = (source / f'{stem}.handlers.lua').read_text()
    for key, value in placeholders.items():
        assert handlers.count(key + ', ') == 1, key
        handlers = handlers.replace(key + ', ', value + ', ')
    text += handlers + '\n'
    registered =sorted(set(events) | entity_events)
    for event_id in registered:
        title = events.get(event_id, str(event_id)).replace('_', ' ').capitalize()
        title = title.replace('Armoury', 'Armory').replace('armoury', 'armory')
        text += f'if type(handlers[{event_id}]) == "function" then\n'
        text += f'    RegisterEvent({event_id}, {json.dumps(title)}, handlers[{event_id}], {json.dumps(title)})\nend\n'
    (runtime / f'{stem}.lua').write_text(text)

    tree = runtime / 'worlds/hesper'
    (tree / 'maps').mkdir(parents=True, exist_ok=True)
    (tree / 'events/maps').mkdir(parents=True, exist_ok=True)
    shutil.copy2(runtime / map_file, tree / 'maps' / map_file)
    shutil.copy2(runtime / f'{stem}.scene.yml', tree / 'maps' / f'{stem}.scene.yml')
    shutil.copy2(runtime / f'{stem}.lua', tree / 'events/maps' / f'{stem}.lua')
    report = {'map': map_file, 'faces': len(native['faces']), 'vertices': len(native['vertices']),
              'sectors': len(native['sectors']), 'portals': sum(1 for f in native['faces'] if f['is_portal']),
              'doors': len(doors), 'lights': len(native['lights']), 'decorations': len(native['entities']),
              'events': sorted(bound | entity_events)}
    (project / f'{stem.replace("hes_", "")}_build.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report))
    return report
