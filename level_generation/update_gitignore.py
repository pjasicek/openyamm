#!/usr/bin/env python3
"""Refresh the generated tail of level_generation/.gitignore.

The hand-written rules above the marker choose what level_generation tracks by folder and extension. Git cannot
filter by size, so this lists every file those rules would let through that is over the size limit (generated
viewers with embedded images, large manifests and catalogues), plus symbolic links, and ignores them by path.
Files that git already tracks, and files named one by one with `!/path` above the marker, are left alone.
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
GITIGNORE = HERE / '.gitignore'
MARKER = '# --- Generated by update_gitignore.py:'
DEFAULT_LIMIT = 256 * 1024


def escapePattern(path: str) -> str:
    """Anchor a relative path as a literal gitignore pattern."""
    escaped = ''.join('\\' + c if c in '*?[\\' else c for c in path)
    if escaped.endswith(' '):
        escaped = escaped[:-1] + '\\ '
    return '/' + escaped


def exposedFiles() -> list[str]:
    output = subprocess.run(['git', 'ls-files', '-z', '--others', '--exclude-standard', '--', '.'],
                            cwd=HERE, check=True, capture_output=True).stdout
    return [p for p in output.decode('utf-8', 'surrogateescape').split('\0') if p]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--limit-kb', type=int, default=DEFAULT_LIMIT // 1024, help='size limit in KB (default 256)')
    args = parser.parse_args()
    limit = args.limit_kb * 1024

    text = GITIGNORE.read_text()
    markerAt = text.find(MARKER)
    if markerAt < 0:
        print(f'{GITIGNORE}: marker line not found', file=sys.stderr)
        return 1
    markerEnd = text.index('\n', markerAt) + 1
    head = text[:markerEnd]
    # Hand-written exceptions such as `!/ui/.../placements.json` keep their file whatever its size.
    explicit = {line[2:] for line in head.splitlines() if line.startswith('!/') and not any(c in line for c in '*?[')}

    # List with the hand-written rules alone, so files that shrank or were removed drop out of the list.
    GITIGNORE.write_text(head)
    try:
        candidates = exposedFiles()
    except BaseException:
        GITIGNORE.write_text(text)
        raise

    excluded = []
    keptBytes = 0
    for path in candidates:
        info = os.lstat(HERE / path)
        if os.path.islink(HERE / path) or (info.st_size > limit and path not in explicit):
            excluded.append(path)
        else:
            keptBytes += info.st_size
    excluded.sort()

    GITIGNORE.write_text(head + ''.join(escapePattern(p) + '\n' for p in excluded))
    print(f'{len(candidates) - len(excluded)} untracked files allowed ({keptBytes / 1e6:.1f} MB), '
          f'{len(excluded)} over {args.limit_kb} KB or links listed in {GITIGNORE.name}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
