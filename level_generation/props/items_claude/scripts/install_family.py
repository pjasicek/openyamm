"""Install a family's item models and rewrite the item model bindings.

Per icon of work/<family>_manifest.json: check work/<family>/<icon>_export.glb with the winding check (0 inverted
closed parts), install it as engine/world_items/models/item_<icon>.glb (tools/install_model.py --world-items; the model cook needs the
files directly in models/), then rewrite assets_dev/engine/world_items/items.yml from every family's manifest whose models
are installed: {icon, model, length} per icon.
Lengths in work/length_overrides.json and the designs' lengths (designs.json) replace the manifests' icon-based
lengths. `meshy` installs every 3D design of designs.json for its icons (GROUND_ITEM_3D_PLAYBOOK.md).
Usage: python3 -I install_family.py <family|meshy> [--bindings-only]"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
WINDING = os.path.join(REPO, 'level_generation', 'decorations', 'mm8_3d', 'animated', 'scripts', 'check_winding.py')
BINDINGS = os.path.join(REPO, 'assets_dev', 'engine', 'world_items', 'items.yml')
HEADER = '''# 3D models of items lying on the ground, by inventory icon (items.txt "Pic File"): items sharing an icon share a
# model. A bound item draws its model, in its baked resting pose with a yaw of its own, instead of its sprite.
# length: world units of the model's longest horizontal side (the icon's opaque height in logical pixels x 0.9).
# Generated by level_generation/props/items_claude/scripts/install_family.py; see GROUND_ITEMS_3D_PLAN.md.
schema: openyamm.itemModels.v1
items:
'''


def install(export, icon):
    subprocess.run([sys.executable, os.path.join(REPO, 'tools', 'install_model.py'), export, '--world-items',
                    '--name', f'item_{icon}.glb'], check=True, capture_output=True)


def main():
    family = sys.argv[1]
    if family == 'meshy':
        # The 3D designs of designs.json, each installed for its icons: route 'codex' (Smart Topology with
        # Codex-painted PBR, work/codex_tex/<design>) or 'meshy_textured' (work/meshy/<design>).
        designs = json.load(open(os.path.join(HERE, 'designs.json')))
        if '--bindings-only' not in sys.argv:
            for design, entry in designs.items():
                folder = 'codex_tex' if entry['route'] == 'codex' else 'meshy'
                export = os.path.join(HERE, 'work', folder, f'{design}_export.glb')
                check = subprocess.run([sys.executable, WINDING, export], capture_output=True, text=True, check=True)
                if not check.stdout.strip().endswith(': 0'):
                    raise SystemExit(f'{design}: {check.stdout.strip()}')
                for icon in entry['icons']:
                    install(export, icon)
                    print('installed', icon, design)
        manifest = {}
    else:
        manifest = json.load(open(os.path.join(HERE, 'work', f'{family}_manifest.json')))
    if family != 'meshy' and '--bindings-only' not in sys.argv:
        for icon in manifest:
            export = os.path.join(HERE, 'work', family, f'{icon}_export.glb')
            check = subprocess.run([sys.executable, WINDING, export], capture_output=True, text=True, check=True)
            if not check.stdout.strip().endswith(': 0'):
                raise SystemExit(f'{icon}: {check.stdout.strip()}')
            install(export, icon)
            print('installed', icon)
        # A model cook running elsewhere at the same time can drop a runtime copy whose source it has not seen yet.
        for icon in manifest:
            if not os.path.exists(os.path.join(REPO, 'assets_dev', 'engine', 'world_items', 'models', f'item_{icon}.glb')):
                install(os.path.join(HERE, 'work', family, f'{icon}_export.glb'), icon)
                print('reinstalled', icon)
    lines = []
    # Lengths set by hand (books share one size; the Meshy designs), over the manifests' icon-based lengths.
    overrides = json.load(open(os.path.join(HERE, 'work', 'length_overrides.json')))
    for entry in json.load(open(os.path.join(HERE, 'designs.json'))).values():
        overrides.update({icon: entry['length'] for icon in entry['icons']})
    for name in sorted(os.listdir(os.path.join(HERE, 'work'))):
        if not name.endswith('_manifest.json'):
            continue
        for icon, entry in sorted(json.load(open(os.path.join(HERE, 'work', name))).items()):
            model = f'engine/world_items/models/item_{icon}.glb'
            if os.path.exists(os.path.join(REPO, 'assets_dev', model)):
                users = ', '.join(sorted({user['name'] for user in entry['items']}))
                length = overrides.get(icon, entry['length'])
                lines.append(f'  - {{icon: {icon}, model: {model}, length: {length}}}   # {users}\n')
    with open(BINDINGS, 'w') as handle:
        handle.write(HEADER + ''.join(lines))
    print('bindings', len(lines))


main()
