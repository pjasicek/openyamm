"""Console script laying out one item per installed icon on the open plain of MM7 out10.odm ->
testmap/out10_all_items.cfg, for `exec <path>` in the debug console: every monster killed, then the families in rows
(the order below), each family's items spaced by its median length, each dropped from 100 units above the terrain
under it. The plain (x -8704 to -512, y 11264 to 17408) lies well inside the map's travel bounds (+-23143) and has no
b-models or decorations. Start the party at -4608 17700 facing south (yaw -1.5708).
Usage: python3 -I make_testmap.py"""
import json
import os
import statistics
import sys
from pathlib import Path

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'util'))
from map_export import parse_odm_file  # noqa: E402

MAP = os.path.join(REPO, 'assets_dev', 'worlds', 'mm7', 'maps', 'out10.odm')
ORDER = ['swords', 'daggers', 'axes', 'maces', 'spears', 'staves', 'bows', 'blasters', 'wands', 'shields', 'armour',
         'helms', 'boots', 'gauntlets', 'cloaks', 'belts', 'rings', 'amulets', 'gems', 'lumps', 'bottles', 'scrolls',
         'books', 'gold', 'misc']
LEFT, RIGHT, TOP = -8400, -800, 17100
FAMILY_GAP = 110


def terrain_height(heights, x, y):
    """Bilinear height of the native 128 x 128 grid (512 units a cell, x east, y north, origin at the centre)."""
    gx, gy = 64 + x / 512.0, 64 - y / 512.0
    ix, iy = int(gx), int(gy)
    fx, fy = gx - ix, gy - iy

    def at(cx, cy):
        return heights[min(max(cy, 0), 127) * 128 + min(max(cx, 0), 127)] * 32
    upper = at(ix, iy) * (1 - fx) + at(ix + 1, iy) * fx
    lower = at(ix, iy + 1) * (1 - fx) + at(ix + 1, iy + 1) * fx
    return upper * (1 - fy) + lower * fy


def main():
    heights = parse_odm_file(Path(MAP))['payload']['height_map']
    lines = ['# Generated by level_generation/props/items_claude/scripts/make_testmap.py: every ground item model on the',
             '# open plain of MM7 out10.odm; start at -4608 17700 facing south.',
             'actor kill 100000']
    y = TOP
    for family in ORDER:
        manifest = json.load(open(os.path.join(HERE, 'work', f'{family}_manifest.json')))
        spacing = min(max(statistics.median(e['length'] for e in manifest.values()) * 0.7 + 30, 60), 220)
        lines.append(f'# {family}: {len(manifest)} icons, row y {round(y)}')
        x = LEFT
        for icon in sorted(manifest):
            if x > RIGHT:
                x, y = LEFT, y - spacing
            z = terrain_height(heights, x, y) + 100
            lines.append(f'item drop {manifest[icon]["items"][0]["id"]} {round(x)} {round(y)} {round(z)}')
            x += spacing
        y -= spacing + FAMILY_GAP
    out = os.path.join(HERE, 'testmap', 'out10_all_items.cfg')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w') as handle:
        handle.write('\n'.join(lines) + '\n')
    print(out, sum(line.startswith('item drop') for line in lines), 'drops, last row y', round(y))


main()
