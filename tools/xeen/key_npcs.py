#!/usr/bin/env python3
"""Xeen's placed talking figures: who they are, what they look like, and that a stray blow cannot kill them.

A placed figure is an actor of an installed Xeen scene with an NPC id (`npc_id`: a teacher, quest giver, merchant or
any other talker) or on a `characters:` row of source/monsters.yml (Corak, Crodo, the caged prisoners). Feedback F9
(2026-11-21): Sablewing, the dragon hermit who teaches the Dragon Master, stood on a peasant row, inspected as
"Peasant" and could be killed, and his teaching died with him.

The rule, world-wide: a placed figure takes no damage while it is not hostile to the party
(evt.SetMm9ActorCanReceiveDamage, as MM9's CanDamage and D-51's Corak), so no blow, missile or spell hurts it or turns
it. When its own story turns it on the party (Q-D12's "Battle!" for Yog, a faction's relation rule), it can be fought.
This tool writes that list, map by map, into events/common/xeen_key_npcs.lua (generated: never edit it), whose global
load event and one-second timer apply it on every Xeen map.

    python3 tools/xeen/key_npcs.py            check: the list matches the installed scenes, every figure shows its own
                                              name, and none stands on a generic body row; exit 1 on an error
    python3 tools/xeen/key_npcs.py --write    write the Lua list from the installed scenes (after a map is installed)
    python3 tools/xeen/key_npcs.py --list     print every figure with its name, body and protection

The name a figure shows is the engine's (ActorNameResolver): a placed name (unique_name_index), then, for an actor with
an NPC id, the NPC's name (the original games' rule; A1 spec F9-R2, until it lands the row's name), then its row's.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
WORLD = ROOT / 'assets_dev/worlds/xeen'
LUA = WORLD / 'events/common/xeen_key_npcs.lua'
# Engine rows a named figure must not stand on: the generic townsfolk, whose name ("Peasant") hides who they are
# until F9-R2 and whose body says nothing of them. A figure on one is listed; it is an error only when it also has
# no NPC id (nothing could ever show its name).
GENERIC_ROW_NAMES = {'Peasant'}
# Bodies chosen against the NPC's portrait and title (F9 audit, 2026-11-21): NPC id -> what the body must read as. A
# figure listed here whose row's picture does not contain the word is an error.
BODY_EXPECTATIONS = {
    4720: 'Xeen Sablewing',   # the dragon hermit: a dragon (his portrait), not a peasant
    4529: 'Xeen Elder Druid',  # the Winter Druid (X5): an old bearded man (his portrait), robed (D91 §1)
    4048: 'Xeen Elder Druid',  # the Spring Druid (X1): the same (D91 §1)
    4321: 'Xeen Druidess',     # the Autumn Druid (X4): a druid woman (her portrait), friendly row 11929 (D91 §1)
    4601: 'Xeen Druidess',     # the Summer Druid (X6): the same (D91 §1)
}


def table_rows(path):
    rows = {}
    if path.exists():
        for line in path.read_text(encoding='utf-8', errors='replace').splitlines():
            cells = line.split('\t')
            if cells and cells[0].strip().isdigit():
                rows[int(cells[0])] = cells
    return rows


ACTOR = re.compile(r'- actor_index: (\d+)\n\s+name: (.*)\n\s+npc_id: (\d+)\n\s+attributes: (\d+)\n(?:.*\n){1,3}?'
                   r'\s+monster_info_id: (\d+)\n')


def placed_figures(characters):
    """(stem, actor index, npc id, monster id, unique name index, attributes) for every placed figure."""
    figures = []
    for scene in sorted((WORLD / 'maps').glob('*.scene.yml')):
        stem = scene.name[:-len('.scene.yml')]
        text = scene.read_text(encoding='utf-8')
        matches = list(ACTOR.finditer(text))
        for number, match in enumerate(matches):
            index, _name, npc, attributes, monster = match.groups()
            end = matches[number + 1].start() if number + 1 < len(matches) else len(text)
            unique = re.search(r'unique_name_index: (\d+)', text[match.end():end])
            if int(npc) or int(monster) in characters:
                figures.append((stem, int(index), int(npc), int(monster), int(unique.group(1)) if unique else 0,
                                int(attributes)))
    return figures


def map_names():
    """Map file stem -> its map_stats name, which evt.GetCurrentMapName() returns (Xeen.onMap)."""
    result = {}
    for cells in table_rows(WORLD / 'data_tables/map_stats.txt').values():
        if len(cells) > 2 and cells[2].strip():
            result[cells[2].strip().rsplit('.', 1)[0].lower()] = cells[1].strip()
    return result


def lua_text(figures, names, stem_names):
    lines = ['-- Generated by tools/xeen/key_npcs.py from the installed scenes; do not edit (run it with --write after a',
             '-- map is installed). Feedback F9 (devdocs/xeen/reviews/USER_FEEDBACK_20261121.md): every placed talking',
             '-- figure (an NPC id or a monsters.yml character) takes no damage while it is not hostile to the party, so no',
             "-- stray blow kills a teacher or turns a quest giver; its story's own turn (Q-D12's \"Battle!\") lifts it.",
             '-- Owner: the tool (lanes A4 and S keep it current; xeen_common.lua is A3\'s).',
             '',
             'XeenKeyNpcs = {}',
             '-- map name (map_stats, as evt.GetCurrentMapName() gives it) -> {actor index, ...}; the comment names each figure',
             'XeenKeyNpcs.maps = {']
    by_map = {}
    for stem, index, npc, monster, _unique, _attributes in figures:
        by_map.setdefault(stem, []).append((index, names(npc, monster)))
    for stem in sorted(by_map):
        entries = ', '.join(str(index) for index, _ in by_map[stem])
        who = '; '.join(f'{index} {name}' for index, name in by_map[stem])
        lines.append(f'    ["{stem_names[stem]}"] = {{{entries}}},  -- {stem}: {who}')
    lines += ['}',
              '',
              '-- Damage off for the current map\'s figures while they are friendly, on once one is hostile to the party.',
              'function XeenKeyNpcs.apply()',
              '    local list = XeenKeyNpcs.maps[evt.GetCurrentMapName() or ""]',
              '    if list == nil then',
              '        return',
              '    end',
              '    for _, actor in ipairs(list) do',
              '        evt.SetMm9ActorCanReceiveDamage(actor, evt.IsMapActorHostile(actor))',
              '    end',
              'end',
              '',
              '-- 49998/49999: QUESTS_FORMAT block 199, kept for this file.',
              'RegisterGlobalOnLoadEvent(49998, nil, XeenKeyNpcs.apply)',
              '-- 30 game seconds, about one real second: a figure its story has just turned can be fought.',
              'RegisterGlobalTimerEvent(49999, 30, XeenKeyNpcs.apply)',
              '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()

    source = yaml.safe_load((WORLD / 'source/monsters.yml').read_text())
    characters = {entry['id']: entry for entry in source.get('characters') or []}
    npcs = table_rows(WORLD / 'data_tables/npc.txt')
    monsters = table_rows(ROOT / 'assets_dev/engine/data_tables/monster_data.txt')
    monsters.update(table_rows(WORLD / 'data_tables/monster_data.txt'))
    placed_names = table_rows(WORLD / 'data_tables/english/place_mon.txt')

    def names(npc, monster):
        if npc and npc in npcs:
            return npcs[npc][1]
        return monsters[monster][1] if monster in monsters else f'monster {monster}'

    figures = placed_figures(characters)
    stem_names = map_names()
    errors = []
    for stem in sorted({figure[0] for figure in figures}):
        if stem not in stem_names:
            errors.append(f'{stem}: no map_stats row, so the Lua cannot find the map by name')
            stem_names[stem] = stem
    duplicates = {name for name in stem_names.values() if list(stem_names.values()).count(name) > 1}
    for stem in sorted({figure[0] for figure in figures}):
        if stem_names[stem] in duplicates:
            errors.append(f'{stem}: its map name "{stem_names[stem]}" is shared with another map')
    text = lua_text(figures, names, stem_names)
    if args.write:
        if errors:
            print('\n'.join('ERROR ' + error for error in errors))
            return 1
        LUA.write_text(text, encoding='utf-8')
        print(f'wrote {LUA.relative_to(ROOT)}: {len(figures)} figures on {len({f[0] for f in figures})} maps')
        return 0

    if not LUA.exists() or LUA.read_text(encoding='utf-8') != text:
        errors.append(f'{LUA.relative_to(ROOT)} does not match the installed scenes: run key_npcs.py --write')
    for stem, index, npc, monster, unique, attributes in figures:
        row = monsters.get(monster)
        row_name = row[1] if row else '?'
        picture = row[2] if row else '?'
        own = names(npc, monster)
        shown = placed_names[unique][1] if unique in placed_names else row_name
        after_r2 = placed_names[unique][1] if unique in placed_names else (own if npc else row_name)
        problems = []
        if row is None:
            problems.append('no monster row')
        if after_r2 != own:
            problems.append(f'shows "{after_r2}", not its own name')
            errors.append(f'{stem} actor {index} ({own}): shows "{after_r2}"')
        if row_name in GENERIC_ROW_NAMES:
            problems.append(f'generic body row {monster} ({picture}); shows "{shown}" until F9-R2')
        if npc in BODY_EXPECTATIONS and BODY_EXPECTATIONS[npc] not in picture:
            problems.append(f'body {picture}, wants {BODY_EXPECTATIONS[npc]}')
            errors.append(f'{stem} actor {index} ({own}): body {picture}, wants {BODY_EXPECTATIONS[npc]}')
        if args.list or problems:
            print(f'{stem:11} actor {index:4} npc {npc:5} {own[:24]:24} row {monster:6} {picture[:30]:30} '
                  f'{"; ".join(problems) or "ok"}')
    generic = sum(1 for f in figures if monsters.get(f[3], ['', ''])[1] in GENERIC_ROW_NAMES)
    print(f'{len(figures)} placed figures on {len({f[0] for f in figures})} maps, all protected by '
          f'{LUA.name}; {generic} on generic peasant rows (named by F9-R2); {len(errors)} errors')
    for error in errors:
        print('ERROR', error)
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())
