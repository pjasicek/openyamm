# Keyed by a map file, which must have a map_stats row of this world.
MAP_KEYED_TABLES = {'house_exits.txt', 'outdoor_travels.txt', 'map_navigation.txt'}


class BuildContext:
    def __init__(self, world: World):
        self.world = world
        self.tables: dict[str, Table] = {}
        self.texts: dict[str, tuple[str, list[str]]] = {}
        self.shared: dict[str, object] = {}
        self.warnings: list[str] = []
        self.current_module = ''
        # output path -> the modules that added to it (build_world.py --only writes one module's files)
        self.writers: dict[Path, set[str]] = {}
        self._maps = None

    # Sources -----------------------------------------------------------------------------------------------------

    def load_source(self, relative: str, required: bool = True):
        path = SOURCE / relative
        if not path.exists():
            if required:
                raise BuildError(f'{path} does not exist')
            return None
        try:
            return load_yaml(path)
        except yaml.YAMLError as error:
            raise BuildError(f'{path}: {error}') from error

    @property
    def maps(self) -> list[dict]:
        """The orchestrator's map registry (source/maps.yml), read once."""
        if self._maps is None:
            self._maps = (self.load_source('maps.yml') or {}).get('maps') or []
        return self._maps

    def map_by_key(self, key: str) -> dict:
        for entry in self.maps:
            if entry.get('key') == key:
                return entry
        raise BuildError(f'maps.yml has no map {key}')

    # Outputs -----------------------------------------------------------------------------------------------------

    def table(self, file: str, sources: list[str] | None = None, **kwargs) -> Table:
        """The table `file`, created on first use; a later module asking for the same file appends to it."""
        if file not in self.tables:
            self.tables[file] = Table(file, **kwargs)
        table = self.tables[file]
        table.sources.update(sources or [])
        self.writers.setdefault(DATA_TABLES / file, set()).add(self.current_module)
        return table

    def text(self, relative: str, content: str, sources: list[str]):
        """A generated text file at the world root (relations.yml) or below it. The generated note is added."""
        if relative in self.texts:
            raise BuildError(f'{relative} is written by two modules')
        self.texts[relative] = (content, sources)
        self.writers.setdefault(WORLD / relative, set()).add(self.current_module)

    def ensure_contribution_tables(self, keep_existing: bool):
        """Every file of CONTRIBUTION_TABLES, header-only where no module filled it. keep_existing: a module was
        skipped, so a file already on disk is left as it is (its module's last output)."""
        for file, arguments in CONTRIBUTION_TABLES.items():
            if file in self.tables or (keep_existing and (DATA_TABLES / file).exists()):
                continue
            self.table(file, sources=['no rows yet'], **arguments)

    def warn(self, message: str):
        self.warnings.append(f'{self.current_module}: {message}' if self.current_module else message)

    # Checks ------------------------------------------------------------------------------------------------------

    def check(self) -> list[str]:
        problems = list(self.world.check_ranges())
        for table in self.tables.values():
            problems.extend(self._check_table(table))
        stems = set()
        if 'map_stats.txt' in self.tables:
            stems = {cell(row, 2).lower() for row in self.tables['map_stats.txt'].rows}
        for file in MAP_KEYED_TABLES & set(self.tables):
            for row in self.tables[file].rows:
                if cell(row, 0).lower() not in stems:
                    problems.append(f'{file} row {cell(row, 0)!r}: the map has no map_stats row of this world')
        return problems

    def _check_table(self, table: Table) -> list[str]:
        problems = []
        seen: dict[object, str] = {}
        engine_keys = set()
        if table.engine is not None:
            engine_keys = table_keys(engine_table(table.engine), table.key_column, table.numeric_key)
        other_keys = self.world.other_contribution_keys(table.contribution, table.key_column, table.numeric_key)
        id_range = self.world.id_range(table.domain) if table.domain else None
        for row, origin in zip(table.rows, table.origins):
            raw = cell(row, table.key_column)
            key = parse_int(raw) if table.numeric_key else raw.lower()
            where = f'{table.file} row {raw!r}' + (f' ({origin})' if origin else '')
            if key is None or key == '':
                problems.append(f'{where}: no key')
                continue
            if id_range and not id_range[0] <= key <= id_range[1]:
                problems.append(f'{where}: outside idRanges.{table.domain} {id_range[0]}-{id_range[1]}')
            if key in seen:
                problems.append(f'{where}: the same key as {seen[key]}')
            seen[key] = origin or raw
            if table.rewords:
                if key not in engine_keys:
                    problems.append(f'{where}: rewords a row the engine table {table.engine} does not have')
                continue
            if key in engine_keys:
                problems.append(f'{where}: the engine table {table.engine} already has this key')
            if key in other_keys:
                problems.append(f'{where}: world {other_keys[key]} already contributes this key')
        return problems

    # Results -----------------------------------------------------------------------------------------------------

    def outputs(self) -> dict[Path, str]:
        files = {}
        for table in self.tables.values():
            files[DATA_TABLES / table.file] = table.text()
        for relative, (content, sources) in self.texts.items():
            comment = '--' if relative.endswith('.lua') else '#'
            note = f"{comment} Generated by {GENERATOR} from {', '.join(sources)}; do not edit.\n"
            files[WORLD / relative] = note + content
        return files


def is_generated(path: Path) -> bool:
    """A file the generator wrote: its generated note, or a table without one (only the generator writes there)."""
    if path.parent == DATA_TABLES and path.suffix == '.txt':
        return True
    try:
        with open(path, encoding='utf-8', errors='replace') as handle:
            first = handle.readline()
            return first.startswith(f'# Generated by {GENERATOR}') or first.startswith(f'-- Generated by {GENERATOR}')
    except OSError:
        return False


def fail(message: str):
    print(f'error: {message}', file=sys.stderr)
    sys.exit(1)
