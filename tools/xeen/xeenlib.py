"""Shared pieces of the Xeen world generator (tools/xeen/build_world.py).

The driver builds one BuildContext, hands it to every module in turn (each module has `build(ctx)`), then checks and
writes everything the modules added. A module never writes a file itself:

    def build(ctx):
        source = ctx.load_source('monsters.yml')            # assets_dev/worlds/xeen/source/monsters.yml
        table = ctx.table('monster_data.txt', domain='monsters', engine='monster_data.txt', header_rows=4)
        table.add([11010, 'Goblin', ...], origin='monsters.yml goblins A')
        ctx.text('relations.yml', yaml_text, sources=['monsters.yml'])   # a world-root file
        ctx.shared['monsters'] = {...}                       # what later modules may read

Tables are TSV files in assets_dev/worlds/xeen/data_tables/. Their first line is a comment row
("# Generated by tools/xeen/build_world.py ...") that the table loaders skip like any row without a numeric id; the
header rows copied from the engine table follow it, then the rows. The driver stops on any id outside the world's
idRanges, any id twice in one table, and any id an engine table or another world's contribution already uses.
Plain Python and PyYAML only.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'assets_dev'
ENGINE_TABLES = ASSETS / 'engine' / 'data_tables'
WORLDS = ASSETS / 'worlds'
WORLD_ID = 'xeen'
WORLD = WORLDS / WORLD_ID
SOURCE = WORLD / 'source'
DATA_TABLES = WORLD / 'data_tables'
GENERATOR = 'tools/xeen/build_world.py'


class BuildError(Exception):
    """A problem that stops the build (bad source data, an id out of range or colliding)."""


# ---------------------------------------------------------------------------------------------------------------------
# Reading files


def load_yaml(path: Path):
    with open(path, encoding='utf-8') as handle:
        return yaml.safe_load(handle)


def read_tsv(path: Path) -> list[list[str]]:
    """Rows of a tab-separated table, line endings removed (the engine tables mix CRLF and LF)."""
    with open(path, encoding='utf-8', errors='replace', newline='') as handle:
        text = handle.read()
    return [line.split('\t') for line in text.replace('\r\n', '\n').replace('\r', '\n').split('\n') if line != '']


def cell(row: list[str], index: int) -> str:
    return row[index].strip() if index < len(row) else ''


def parse_int(value) -> int | None:
    text = str(value).strip().strip('"')
    if text.isdigit():
        return int(text)
    return None


_engine_cache: dict[str, list[list[str]]] = {}


def engine_table(name: str) -> list[list[str]]:
    """An engine table's rows (assets_dev/engine/data_tables/<name>), read once."""
    if name not in _engine_cache:
        path = ENGINE_TABLES / name
        if not path.exists():
            raise BuildError(f'engine table {path} does not exist')
        _engine_cache[name] = read_tsv(path)
    return _engine_cache[name]


def table_keys(rows: list[list[str]], column: int, numeric: bool) -> set:
    keys = set()
    for row in rows:
        value = cell(row, column)
        if numeric:
            number = parse_int(value)
            if number is not None:
                keys.add(number)
        elif value and not value.startswith('#'):
            keys.add(value.lower())
    return keys


# ---------------------------------------------------------------------------------------------------------------------
# Writing


def format_cell(value) -> str:
    if value is None:
        return ''
    if isinstance(value, bool):
        return 'x' if value else '-'
    if isinstance(value, float):
        text = f'{value:.3f}'.rstrip('0').rstrip('.')
        return text if text else '0'
    text = str(value)
    if '\t' in text or '\r' in text:
        raise BuildError(f'a table cell holds a tab or a carriage return: {text!r}')
    if '\n' in text and not (len(text) >= 2 and text.startswith('"') and text.endswith('"')):
        raise BuildError(f'a table cell holds a line break outside quotes (use quote_text): {text!r}')
    return text


def quote_text(text: str) -> str:
    """A free-text cell as the engine tables write one: in double quotes, inner quotes doubled, when it holds a
    comma, a quote or a line break (engine/TextTable.cpp reads a quoted cell across lines; a tab is never allowed)."""
    if ',' in text or '"' in text or '\n' in text:
        return '"' + text.replace('"', '""') + '"'
    return text


def dump_yaml(data) -> str:
    """YAML with keys in their given order, short lists and maps on one line."""

    class Dumper(yaml.SafeDumper):
        pass

    def represent_dict(dumper, value):
        flow = all(not isinstance(item, (dict, list)) for item in value.values()) and len(value) <= 8
        return dumper.represent_mapping('tag:yaml.org,2002:map', value.items(), flow_style=flow)

    def represent_list(dumper, value):
        flow = all(not isinstance(item, (dict, list)) for item in value)
        return dumper.represent_sequence('tag:yaml.org,2002:seq', value, flow_style=flow)

    Dumper.add_representer(dict, represent_dict)
    Dumper.add_representer(list, represent_list)
    return yaml.dump(data, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=120)


# ---------------------------------------------------------------------------------------------------------------------
# The world and its id ranges


class World:
    def __init__(self):
        manifest_path = WORLD / 'world.yml'
        if not manifest_path.exists():
            raise BuildError(f'{manifest_path} does not exist')
        self.manifest = load_yaml(manifest_path) or {}
        self.id_ranges = {name: (int(value['begin']), int(value['end']))
                          for name, value in (self.manifest.get('idRanges') or {}).items()}
        self.other_worlds = self._other_worlds()

    def _other_worlds(self) -> list[dict]:
        worlds = []
        for path in sorted(WORLDS.glob('*/world.yml')):
            if path.parent.name == WORLD_ID:
                continue
            try:
                manifest = load_yaml(path) or {}
            except yaml.YAMLError:
                continue
            manifest['_dir'] = path.parent
            worlds.append(manifest)
        return worlds

    def id_range(self, domain: str) -> tuple[int, int]:
        if domain not in self.id_ranges:
            raise BuildError(f'world.yml has no idRanges.{domain}')
        return self.id_ranges[domain]

    def check_ranges(self) -> list[str]:
        """Our ranges against every other world's ranges of the same domain."""
        problems = []
        for manifest in self.other_worlds:
            for domain, value in (manifest.get('idRanges') or {}).items():
                if domain not in self.id_ranges:
                    continue
                begin, end = self.id_ranges[domain]
                if int(value['begin']) <= end and begin <= int(value['end']):
                    problems.append(f'idRanges.{domain} {begin}-{end} overlaps world '
                                    f"{manifest.get('id')}'s {value['begin']}-{value['end']}")
        return problems

    def other_contribution_keys(self, table: str, column: int, numeric: bool) -> dict[object, str]:
        """Keys other worlds already contribute to a table (from their world.yml tableContributions)."""
        keys = {}
        for manifest in self.other_worlds:
            for contribution in manifest.get('tableContributions') or []:
                if contribution.get('table') != table or not contribution.get('path'):
                    continue
                path = manifest['_dir'] / contribution['path']
                if path.exists():
                    for key in table_keys(read_tsv(path), column, numeric):
                        keys[key] = manifest.get('id')
        return keys


# ---------------------------------------------------------------------------------------------------------------------
# Tables


class Table:
    """One generated TSV table in data_tables/.

    file: the file name in data_tables/ (`monster_data.txt`).
    contribution: the engine's table name in world.yml tableContributions (`monster_data`); used to find the rows
      other worlds contribute to the same table.
    domain: the world.yml idRanges domain the row ids must lie in (None: keyed by text, no range).
    engine: the engine table whose header rows are copied and whose keys a row must not repeat.
    header_rows: how many leading rows of the engine table are its header (copied as they are); header_start: the
      first of them to copy (house_exits keeps only its fourth row, the column names).
    header: header rows given directly instead of copying them from the engine table.
    key_column: the column holding each row's id or key; numeric_key: whether it is an integer id.
    note: whether the file starts with the generated comment row. Loaders skip it where rows are keyed by a number;
      a text-keyed table (item_sets, outdoor_travels) has none by default, as its loader would read it as a key.
    rewords: the rows reword rows of the engine table (a `mode: override` contribution, award_texts): each key must be
      one the engine table has, and no id range applies.
    """

    def __init__(self, file, contribution=None, domain=None, engine=None, header_rows=1, header=None,
                 key_column=0, numeric_key=True, note=None, header_start=0, rewords=False):
        self.file = file
        self.rewords = rewords
        self.contribution = contribution or file.rsplit('.', 1)[0]
        self.domain = domain
        self.engine = engine
        self.key_column = key_column
        self.numeric_key = numeric_key
        self.note = numeric_key if note is None else note
        if header is not None:
            self.header = [list(map(str, row)) for row in header]
        elif engine is not None:
            # At most header_rows leading rows, never one with an id (read_tsv drops the engine's blank lines).
            self.header = []
            for row in engine_table(engine)[header_start:header_rows]:
                if numeric_key and parse_int(cell(row, key_column)) is not None:
                    break
                self.header.append(list(row))
        else:
            self.header = []
        self.rows: list[list[str]] = []
        self.origins: list[str] = []
        self.sources: set[str] = set()

    @property
    def width(self) -> int:
        return max([len(row) for row in self.header] + [0])

    def add(self, cells: list, origin: str = ''):
        row = [format_cell(value) for value in cells]
        if self.width and len(row) > self.width:
            raise BuildError(f'{self.file}: a row has {len(row)} cells, the header {self.width} ({origin})')
        self.rows.append(row)
        self.origins.append(origin)

    def text(self) -> str:
        note = f"# Generated by {GENERATOR} from {', '.join(sorted(self.sources)) or 'source data'}; do not edit."
        lines = ([note] if self.note else []) + ['\t'.join(row) for row in self.header]
        width = self.width
        for row in self.rows:
            padded = row + [''] * (width - len(row)) if width else row
            lines.append('\t'.join(padded))
        return '\n'.join(lines) + '\n'


