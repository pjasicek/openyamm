REACH = 1536          # a settlement: the land within this of one of its house doors (town_feel's TOWN_REACH)
DOOR_CLEAR = 640      # a villager starts at least this far from every house door, open or closed
GIVER_CLEAR = 900     # ... and from every placed talking NPC
SOLID_CLEAR = 192     # ... and from any wall, house, bridge or decoration
RASTER = 64
TOWNSFOLK = re.compile(r'peasant|pesant|merchant|monk|cleric|nobleman|druid|bedraggled', re.I)
AGGRESSOR_BIT = 0x00080000


def ctx_cell_to_world(at):
    return at[0] * 512 - 32768, 32768 - at[1] * 512


def world_to_cell(x, y):
    return round(float((x + 32768) / 512), 2), round(float((32768 - y) / 512), 2)


# ---------------------------------------------------------------- data

def load_data():
    return yaml.safe_load(DATA.read_text())


def load_spots():
    if not SPOTS.exists():
        return {}
    return yaml.safe_load(SPOTS.read_text()) or {}


def monster_rows():
    rows = {}
    for path in (xeenlib.ENGINE_TABLES / 'monster_data.txt', xeenlib.DATA_TABLES / 'monster_data.txt'):
        for line in path.read_text(encoding='latin-1').splitlines():
            f = line.split('\t')
            if len(f) > 12 and f[0].strip().isdigit():
                rows[int(f[0])] = {'name': f[1].strip(), 'picture': f[2].strip(), 'move': f[10].strip(),
                                   'ai': f[11].strip()}
    return rows


# A townsfolk picture's race (the check against a settlement's `races`): the first pattern that matches.
RACES = [(r'dark elf', 'dark elf'), (r'\belf\b', 'elf'), (r'dwarf', 'dwarf'), (r'goblin', 'goblin'),
         (r'lizard', 'lizardman'), (r'ogre', 'ogre'), (r'troll', 'troll'), (r'minotaur', 'minotaur'),
         (r'vampire', 'vampire'), (r'sprite', 'sprite'),
         (r'human|^peasant[fm]\d|merchant|nobleman|cleric|monk|bedraggled|druidess', 'human')]


def race_of(picture):
    p = picture.lower()
    for pattern, race in RACES:
        if re.search(pattern, p):
            return race
    return 'unknown'


def palette_rows(s):
    """A settlement's palette as monster rows (entries are {row, race})."""
    return [int(e['row'] if isinstance(e, dict) else e) for e in s.get('palette') or []]


def kind_of(picture):
    """A villager kind: the picture family without its tier letter (Peasant Elf FemaleA B -> Peasant Elf FemaleA)."""
    return re.sub(r'\s+[A-Fa-f]$', '', picture.strip()).lower()


def bound_pictures():
    bound = set()
    for world in ('mm6', 'mm7', 'mm8', 'xeen'):
        text = (xeenlib.WORLDS / world / 'models' / 'actors.yml').read_text()
        bound.update(m.group(1).strip() for m in re.finditer(r'^- descriptor: (.+)$', text, re.M))
    return bound


def town_houses():
    """{map key: {town name: [house]}} from the town files, alternates left out."""
    out = defaultdict(lambda: defaultdict(list))
    for path in sorted(TOWNS.glob('*.yml')):
        data = yaml.safe_load(path.read_text())
        if not isinstance(data, dict) or not data.get('houses') or not data.get('key'):
            continue
        for house in data['houses']:
            if house.get('alternate_of'):
                continue
            out[data['key']][house.get('town', data.get('town'))].append(house)
    return out


def map_key_stem(key):
    return 'xeen_' + key.lower().replace('-', '')


def sketch_of(key):
    path = BRIEFS / key.lower().replace('-', '') / 'L4' / 'sketch.yml'
    return yaml.load(path.read_text(), Loader=yaml.CSafeLoader) if path.exists() else None


def structure_points(sketch):
    """Every structure id (and part id) of the sketch -> its centre [x, y] in cells."""
    points = {}
    for s in (sketch or {}).get('structures') or []:
        at = s.get('at') or (s.get('line') or [None])[0]
        if s.get('id') and at:
            points[s['id']] = at
    return points


def things(odm):
    out = subprocess.run([str(OYMAP), 'things', str(odm), '--world', 'xeen', '--assets', str(xeenlib.ASSETS),
                          '--json'], capture_output=True)
    if out.returncode:
        raise SystemExit(f'oymap things {odm} failed: {out.stderr.decode("latin-1")[:300]}')
    return yaml.safe_load(out.stdout.decode('latin-1'))['things']


def door_points(all_things):
    """Every door the party clicks to enter, knock at or read (houses, closed houses' panels, mirrors), in world units."""
    pts = []
    for t in all_things:
        effects = ' '.join(t['effects'])
        if t['kind'] == 'house' or 'EnterHouse' in effects or 'useMirror' in effects or \
                (t['kind'] == 'panel' and ('Nobody opens' in effects or 'Locked' in effects or 'Closed' in effects
                                            or 'bolted' in effects.lower() or 'door' in effects.lower())):
            pts.append((t['middle'][0], t['middle'][1]))
    return pts


def settlement_doors(key, town, houses, sketch, all_things):
    """The settlement's house positions (world units): each house's door thing by its sketch structure, else by its
    title among the map's things."""
    points = structure_points(sketch)
    by_title = defaultdict(list)
    for t in all_things:
        if t['kind'] in ('house', 'panel', 'name'):
            by_title[t['title'].strip().lower()].append((t['middle'][0], t['middle'][1]))
    out, missing = [], []
    for h in houses:
        door = str(h.get('door', ''))
        base = door.split('#')[0]
        if base in points:
            out.append(ctx_cell_to_world(points[base]))
        elif by_title.get(str(h.get('name', '')).strip().lower()):
            out.append(by_title[str(h['name']).strip().lower()][0])
        else:
            missing.append(h['id'])
    return out, missing


# ---------------------------------------------------------------- the built map

def scene_of(path):
    return yaml.load(Path(path).read_text(), Loader=yaml.CSafeLoader)


def scene_actors(scene):
    return (scene.get('initial_state') or {}).get('actors') or scene.get('actors') or []


def points_in_polygon(points, poly):
    """Even-odd test of many points against one polygon."""
    x, y = points[:, 0], points[:, 1]
    inside = np.zeros(len(points), bool)
    for (ax, ay), (bx, by) in zip(poly, poly[1:] + poly[:1]):
        if ay == by:
            continue
        crosses = (ay > y) != (by > y)
        at_x = ax + (y - ay) * (bx - ax) / (by - ay)
        inside ^= crosses & (x < at_x)
    return inside


def solid_raster(payload, scene, box):
    """Occupied 64-unit cells inside box (x0, y0, x1, y1): every bmodel face projected (walls as lines, floors, roofs and
    decks as areas) and every decoration, grown by SOLID_CLEAR."""
    x0, y0, x1, y1 = box
    w, h = int((x1 - x0) / RASTER) + 1, int((y1 - y0) / RASTER) + 1
    occ = np.zeros((h, w), bool)
    gx, gy = np.meshgrid(x0 + np.arange(w) * RASTER, y0 + np.arange(h) * RASTER)

    def mark_segment(a, b, r):
        lo_x, hi_x = min(a[0], b[0]) - r, max(a[0], b[0]) + r
        lo_y, hi_y = min(a[1], b[1]) - r, max(a[1], b[1]) + r
        i0, i1 = max(0, int((lo_x - x0) / RASTER)), min(w, int((hi_x - x0) / RASTER) + 2)
        j0, j1 = max(0, int((lo_y - y0) / RASTER)), min(h, int((hi_y - y0) / RASTER) + 2)
        if i0 >= i1 or j0 >= j1:
            return
        px, py = gx[j0:j1, i0:i1], gy[j0:j1, i0:i1]
        dx, dy = b[0] - a[0], b[1] - a[1]
        length = dx * dx + dy * dy
        t = np.zeros_like(px, dtype=float) if length == 0 else \
            np.clip(((px - a[0]) * dx + (py - a[1]) * dy) / length, 0.0, 1.0)
        occ[j0:j1, i0:i1] |= np.hypot(a[0] + t * dx - px, a[1] + t * dy - py) <= r

    def mark_disc(x, y, r):
        mark_segment((x, y), (x, y), r)

    grid = np.column_stack([gx.ravel(), gy.ravel()])
    for model in payload['bmodels']:
        lo, hi = model['bounds_min'], model['bounds_max']
        lx, ly, hx, hy = (lo['x'], lo['y'], hi['x'], hi['y']) if isinstance(lo, dict) else (lo[0], lo[1], hi[0], hi[1])
        if hx < x0 - 512 or lx > x1 + 512 or hy < y0 - 512 or ly > y1 + 512:
            continue
        verts = [(v['x'], v['y']) if isinstance(v, dict) else (v[0], v[1]) for v in model['vertices']]
        for face in model['faces']:
            poly = [verts[i] for i in face['vertex_indices']]
            if len(poly) < 2:
                continue
            xs = [p[0] for p in poly]
            ys = [p[1] for p in poly]
            area = 0.5 * abs(sum(poly[i][0] * poly[i - 1][1] - poly[i - 1][0] * poly[i][1] for i in range(len(poly))))
            if area > 64 * 64:
                sel = ((grid[:, 0] >= min(xs) - SOLID_CLEAR) & (grid[:, 0] <= max(xs) + SOLID_CLEAR) &
                       (grid[:, 1] >= min(ys) - SOLID_CLEAR) & (grid[:, 1] <= max(ys) + SOLID_CLEAR))
                if sel.any():
                    inside = points_in_polygon(grid[sel], poly)
                    occ.reshape(-1)[np.nonzero(sel)[0][inside]] = True
            for a, b in zip(poly, poly[1:] + poly[:1]):
                mark_segment(a, b, SOLID_CLEAR)
    for e in scene.get('entities') or []:
        p = e.get('position') or {}
        if x0 - 256 <= p.get('x', 1e9) <= x1 + 256 and y0 - 256 <= p.get('y', 1e9) <= y1 + 256:
            mark_disc(p['x'], p['y'], 160)
    return occ, (x0, y0)


def land_ok(payload):
    """Walkable land per 512 tile (empty_zones.land_mask: no water, no slope the party cannot climb, not the rim)."""
    import empty_zones
    return empty_zones.land_mask(payload, 'xeen')


def road_distance_fn(sketch):
    segs = []
    for r in (sketch or {}).get('roads') or []:
        line = [ctx_cell_to_world(p) for p in r.get('line') or []]
        segs += list(zip(line, line[1:]))
    for d in (sketch or {}).get('districts') or []:
        for r in d.get('roads') or d.get('lanes') or []:
            line = [ctx_cell_to_world(p) for p in (r.get('line') if isinstance(r, dict) else r) or []]
            segs += list(zip(line, line[1:]))

    def dist(x, y):
        best = 1e9
        for (ax, ay), (bx, by) in segs:
            dx, dy = bx - ax, by - ay
            L = dx * dx + dy * dy
            t = 0 if L == 0 else max(0.0, min(1.0, ((x - ax) * dx + (y - ay) * dy) / L))
            best = min(best, math.hypot(ax + t * dx - x, ay + t * dy - y))
        return best
    return dist


# ---------------------------------------------------------------- placement

def place(key, odm=None, scene_path=None):
    from map_export import parse_odm_file
    data = load_data()
    stem = map_key_stem(key)
    odm = Path(odm or MAPS / f'{stem}.odm')
    scene = scene_of(scene_path or MAPS / f'{stem}.scene.yml')
    payload = parse_odm_file(odm)['payload']
    sketch = sketch_of(key)
    all_things = things(odm)
    doors = door_points(all_things)
    givers = [(a['position']['x'], a['position']['y']) for a in scene_actors(scene) if a.get('npc_id')]
    houses = town_houses()[key]
    land = land_ok(payload)
    road_dist = road_distance_fn(sketch)
    spots = load_spots()
    report = []
    for s in data['settlements']:
        if s['map'] != key or s.get('placed_by') or s.get('exempt'):
            continue
        pts, missing = settlement_doors(key, s['name'], houses.get(s.get('town', s['name']), []), sketch, all_things)
        pts += [ctx_cell_to_world(a) for a in s.get('also_at') or []]
        if not pts:
            raise SystemExit(f'{key} {s["name"]}: no house of the settlement found on the map')
        arr = np.array(pts, float)
        box = (arr[:, 0].min() - REACH, arr[:, 1].min() - REACH, arr[:, 0].max() + REACH, arr[:, 1].max() + REACH)
        occ, (ox, oy) = solid_raster(payload, scene, box)
        avoid = [(ctx_cell_to_world(z['at']), z['radius']) for z in s.get('avoid') or []]
        cands = []
        for j in range(occ.shape[0]):
            for i in range(occ.shape[1]):
                if occ[j, i] or i % 2 or j % 2:
                    continue
                x, y = ox + i * RASTER, oy + j * RASTER
                if np.min(np.hypot(arr[:, 0] - x, arr[:, 1] - y)) > s.get('reach', REACH):
                    continue
                tr, tc = int(64 - y / 512), int(x / 512 + 64)
                if not (0 <= tr < 128 and 0 <= tc < 128 and land[tr, tc]):
                    continue
                if doors and min(math.hypot(dx - x, dy - y) for dx, dy in doors) < DOOR_CLEAR:
                    continue
                if givers and min(math.hypot(gx - x, gy - y) for gx, gy in givers) < GIVER_CLEAR:
                    continue
                if any(math.hypot(p[0] - x, p[1] - y) < r for p, r in avoid):
                    continue
                cands.append((x, y, road_dist(x, y), float(np.min(np.hypot(arr[:, 0] - x, arr[:, 1] - y)))))
        count = s['count']
        if len(cands) < count:
            raise SystemExit(f'{key} {s["name"]}: only {len(cands)} free street points for {count} villagers')
        # farthest-point picking, streets first: a point's score is its distance to the picked ones, less a penalty
        # for being off a road line (the sketch's roads), so they spread along the streets and squares
        c = np.array(cands, float)
        penalty = np.clip(c[:, 2] - 256, 0, None) * 0.75 + np.clip(c[:, 3] - 1000, 0, None) * 0.75
        start = int(np.argmin(np.hypot(c[:, 0] - arr[:, 0].mean(), c[:, 1] - arr[:, 1].mean()) + penalty))
        picked = [start]
        dmin = np.hypot(c[:, 0] - c[start, 0], c[:, 1] - c[start, 1])
        while len(picked) < count:
            k = int(np.argmax(dmin - penalty))
            picked.append(k)
            dmin = np.minimum(dmin, np.hypot(c[:, 0] - c[k, 0], c[:, 1] - c[k, 1]))
        pts_out = [list(world_to_cell(c[k, 0], c[k, 1])) for k in picked]
        spots.setdefault(key, {})[s['name']] = pts_out
        on_road = sum(1 for k in picked if c[k, 2] <= 512)
        report.append(f'{key} {s["name"]}: {count} spots from {len(cands)} free points, {on_road} on a road line'
                      + (f'; houses not found {missing}' if missing else ''))
    header = ('# Generated by tools/xeen/villagers.py --place <map> from the built map (D-96): where each settlement\'s\n'
              '# villagers start, in sketch cells [x, y]. Never edited by hand; the palettes and counts are in\n'
              '# villagers.yml.\n')
    SPOTS.write_text(header + yaml.safe_dump(spots, sort_keys=True, default_flow_style=None, width=120))
    return report


def sketch_actors(key):
    """The villagers of map `key` as sketch actor entries (one per spot, kinds in turn, peaceful, wandering)."""
    data = load_data()
    spots = load_spots().get(key, {})
    out = []
    for s in data['settlements']:
        if s['map'] != key or s.get('placed_by') or s.get('exempt'):
            continue
        at_list = spots.get(s['name'])
        if not at_list:
            raise SystemExit(f'villagers: {key} {s["name"]} has no spots: run tools/xeen/villagers.py --place {key}')
        rows = [str(r) for r in palette_rows(s)]
        for i, at in enumerate(at_list):
            out.append({'monster': rows[i % len(rows)], 'at': list(at), 'spread': 0, 'group': s['group'],
                        'hostile': False, 'notes': f'D-96 villager of {s["name"]} (villagers.yml)'})
    return out


def slots(count):
    """Placeholders a generator leaves where its earlier hand-placed townsfolk stood, so that every other actor keeps
    its scene index (playtests and key_npcs address actors by index): fill() puts villagers into them."""
    return [{'villager_slot': True} for _ in range(count)]


def fill(actors, key):
    """The actor list with map `key`'s villagers in its slots, in order, and the rest appended at the end."""
    villagers = iter(sketch_actors(key))
    out = []
    for actor in actors:
        if actor.get('villager_slot'):
            placed = next(villagers, None)
            if placed is None:
                raise SystemExit(f'villagers: {key} has more slots than villagers (actor indices would move)')
            out.append(placed)
        else:
            out.append(actor)
    return out + list(villagers)


def relations(key):
    data = load_data()
    rows = sorted({int(r) for s in data['settlements'] if s['map'] == key and not s.get('exempt')
                   and not s.get('placed_by') for r in palette_rows(s)})
    return [{'of': rows, 'toward': 'party', 'relation': 'friendly'}] if rows else []


# ---------------------------------------------------------------- the check

def measure(s, mons, scene, all_things, sketch, houses):
    pts, _ = settlement_doors(s['map'], s['name'], houses, sketch, all_things)
    pts += [ctx_cell_to_world(a) for a in s.get('also_at') or []]
    arr = np.array(pts, float) if pts else np.zeros((0, 2))
    palette = set(palette_rows(s))
    found = []
    for a in scene_actors(scene):
        mid = a.get('monster_info_id')
        if mid not in palette or a.get('npc_id'):
            continue
        x, y = a['position']['x'], a['position']['y']
        if len(arr) and np.min(np.hypot(arr[:, 0] - x, arr[:, 1] - y)) <= s.get('reach', REACH):
            found.append(a)
    return found, len(pts)


def floor_of(s, doors):
    """D-96's density floor: 0.45 placed villagers per house door for a town of 8 doors or more (MM6-MM8: low 0.35
    Alvar, median 0.7), at least 3; a hamlet or camp of fewer doors 2."""
    if 'floor' in s:
        return s['floor']
    return max(3, math.ceil(0.45 * doors)) if doors >= 8 else 2


def check_all(verbose=False):
    errors, notes, lines = [], [], []
    data = load_data()
    mons = monster_rows()
    bound = bound_pictures()
    houses = town_houses()
    kinds = {}
    names = set()
    for s in data['settlements']:
        names.add((s['map'], s.get('town', s['name'])))
        if s.get('exempt'):
            continue
        ks = []
        allowed = set(s.get('races') or [])
        if not allowed:
            errors.append(f'villagers: {s["name"]}: no `races` (the races living there)')
        if not s['palette'] and s.get('placed_by'):
            notes.append(f'villagers: {s["name"]}: no fitting townsfolk row yet (pending: {s["placed_by"]})')
            continue
        for entry in s['palette']:
            r = entry['row'] if isinstance(entry, dict) else entry
            row = mons.get(int(r))
            if not row:
                errors.append(f'villagers: {s["name"]}: palette row {r} is not a monster row')
                continue
            # race is a hard rule (the user 2026-11-22: no villager race that does not fit the town)
            race = race_of(row['picture'])
            named = entry.get('race') if isinstance(entry, dict) else None
            if named != race:
                errors.append(f'villagers: {s["name"]}: row {r} ({row["picture"]}) is {race}, the entry says {named}')
            if race not in allowed:
                errors.append(f'villagers: {s["name"]}: row {r} ({row["picture"]}) is {race}; the settlement\'s '
                              f'races are {", ".join(sorted(allowed)) or "none"}')
            if row['picture'] not in bound:
                errors.append(f'villagers: {s["name"]}: row {r} ({row["picture"]}) has no installed 3D model')
            if not TOWNSFOLK.search(row['name'] + ' ' + row['picture']):
                errors.append(f'villagers: {s["name"]}: row {r} ({row["name"]}) is not a townsfolk kind')
            if row['ai'] not in ('Wimp', 'Normal') or row['move'] in ('Stationary', 'Stand', ''):
                notes.append(f'villagers: {s["name"]}: row {r} ({row["name"]}) AI {row["ai"]}, move {row["move"]}')
            ks.append(kind_of(row['picture']))
        kinds[s['name']] = set(ks)
        if not 3 <= len(set(ks)) <= 5:
            errors.append(f'villagers: {s["name"]}: palette has {len(set(ks))} kinds (3-5)')
    for s in data['settlements']:
        for other in s.get('neighbours') or []:
            shared = kinds.get(s['name'], set()) & kinds.get(other, set())
            if len(shared) > 1:
                errors.append(f'villagers: {s["name"]} and its neighbour {other} share {len(shared)} kinds: '
                              f'{", ".join(sorted(shared))}')
    # every settlement of the town files has an entry or an exemption
    for key, towns in houses.items():
        for town, hs in towns.items():
            if (key, town) not in names:
                errors.append(f'villagers: {key} {town} ({len(hs)} houses): no entry in villagers.yml (palette or '
                              f'exemption)')
    by_map = defaultdict(list)
    for s in data['settlements']:
        if not s.get('exempt'):
            by_map[s['map']].append(s)
    for key, ss in sorted(by_map.items()):
        stem = map_key_stem(key)
        odm = MAPS / f'{stem}.odm'
        blv = MAPS / f'{stem}.blv'
        path = odm if odm.exists() else blv
        scene_path = MAPS / f'{stem}.scene.yml'
        if not path.exists() or not scene_path.exists():
            notes.append(f'villagers: {key}: not built')
            continue
        scene = scene_of(scene_path)
        all_things = things(path)
        sketch = sketch_of(key)
        doors = door_points(all_things)
        givers = [(a['position']['x'], a['position']['y']) for a in scene_actors(scene) if a.get('npc_id')]
        for s in ss:
            found, ndoors = measure(s, mons, scene, all_things, sketch, houses[key].get(s.get('town', s['name']), []))
            floor = floor_of(s, ndoors)
            fam = Counter(kind_of(mons[a['monster_info_id']]['picture']) for a in found)
            line = (f'{key:6} {s["name"]:22} doors {ndoors:3}  villagers {len(found):3} (floor {floor:2}, '
                    f'{len(found) / max(ndoors, 1):.2f}/door)  kinds {len(fam)}: '
                    + ', '.join(f'{k} {v}' for k, v in fam.most_common()))
            lines.append(line)
            pending = s.get('placed_by')
            sink = notes if pending else errors
            tag = f' (pending: {pending})' if pending else ''
            if not found:
                sink.append(f'villagers: {key} {s["name"]}: no villagers{tag}')
            elif len(found) < floor:
                sink.append(f'villagers: {key} {s["name"]}: {len(found)} villagers, below its floor {floor}{tag}')
            if found and len(fam) < 2:
                sink.append(f'villagers: {key} {s["name"]}: only one villager kind ({next(iter(fam))}){tag}')
            for a in found:
                x, y = a['position']['x'], a['position']['y']
                where = f'{key} {s["name"]}: villager {a.get("actor_index")} at ({x}, {y})'
                if a.get('attributes', 0) & AGGRESSOR_BIT or a.get('hostility_type'):
                    sink.append(f'villagers: {where} starts hostile')
                near_door = min((math.hypot(dx - x, dy - y) for dx, dy in doors), default=1e9)
                if near_door < DOOR_CLEAR - 64:
                    sink.append(f'villagers: {where} starts {near_door:.0f} from a house door (< {DOOR_CLEAR})')
                near_giver = min((math.hypot(gx - x, gy - y) for gx, gy in givers), default=1e9)
                if near_giver < GIVER_CLEAR - 64:
                    sink.append(f'villagers: {where} starts {near_giver:.0f} from a talking NPC (< {GIVER_CLEAR})')
    if verbose:
        print('\n'.join(lines))
    return errors, notes


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--survey', action='store_true')
    ap.add_argument('--place')
    ap.add_argument('--odm')
    ap.add_argument('--scene')
    args = ap.parse_args()
    if args.place:
        for line in place(args.place, args.odm, args.scene):
            print(line)
        return 0
    errors, notes = check_all(verbose=True)
    for n in notes:
        print(f'  WARN  {n}')
    for e in errors:
        print(f'  ERROR {e}')
    print(f'villagers: {len(errors)} errors, {len(notes)} warnings')
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())
