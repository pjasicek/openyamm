#!/usr/bin/env python3
"""Street villagers of every Xeen settlement (lane A4; decision D-96, the user's F20: "no villagers in the village?").

    python3 tools/xeen/villagers.py                 # the check (towns.py --strict runs it); exit 1 on an error
    python3 tools/xeen/villagers.py --survey        # every settlement: villagers, kinds, density against its floor
    python3 tools/xeen/villagers.py --place X3 [--odm <odm> --scene <scene.yml>]
                                                    # writes X3's street spots into villagers_spots.yml

Data: `source/towns/villagers.yml` (hand-written: each settlement's palette, count and area) and
`source/towns/villagers_spots.yml` (generated by --place from the built map: where each villager starts). A map's
generator places them with two calls:

    sk['actors'] += villagers.sketch_actors('X3')       # at the end of the list, or
    sk['actors'] = villagers.fill(actors, 'X2')          # into villagers.slots(n) left where earlier townsfolk stood
    sk['relations'] += villagers.relations('X3')

(Actor indices of the other actors must not move: playtests and key_npcs address actors by index.)

Rules (D-96): every settlement has peaceful wandering villagers at MM6-MM8's density for its size (placed villagers per
house door: shipped median 0.7, low 0.35; hamlets of 2-6 doors 1-2 each); each has a palette of 3-5 kinds (a kind is a
monster picture family, e.g. "Peasant Elf FemaleA") drawn from the MM6-MM8 townsfolk rows with an installed 3D model;
neighbouring settlements share at most one kind; villagers start on the settlement's streets, clear of house doors and
of talking NPCs.

The check fails (ERROR) a settlement of a built map with no villagers, fewer than its floor, or fewer than two kinds;
a palette outside 3-5 kinds, a kind without a 3D model or a townsfolk name, a kind whose race (from its picture)
the settlement's `races` do not allow (the user: no villager race that does not fit the town), neighbours sharing two
kinds; a villager
that starts hostile, inside a house, within DOOR_CLEAR of a house door or GIVER_CLEAR of a talking NPC; a settlement of
the town files with neither an entry nor an exemption.
"""
