def voice_sexes():
    """{house sound base: sex} of VOICES."""
    return {voice[0]: sex for kinds in VOICES.values() for sex, voice in kinds.items() if voice}


def voice_source_errors():
    """VOICES against the engine: each pair is a house_animations row of the kind's type, and its greeting (sound base
    + 1) is a sound of sounds.txt with a file in the engine's or MM6-MM8's audio."""
    pairs = {(row[7].strip(), row[8].strip().lstrip('0'), row[9].strip())
             for row in read_table('house_animations.txt') if row[0].isdigit() and len(row) > 9}
    sounds = {row[1].strip(): row[0].strip() for row in read_table('sounds.txt') if len(row) > 1}
    files = {path.name.lower() for folder in SOUND_FOLDERS if folder.is_dir() for path in folder.iterdir()}
    errors = []
    for kind, kinds in VOICES.items():
        for sex, voice in kinds.items():
            if not voice:
                continue
            base, portrait = voice
            if (str(base), str(portrait), KINDS[kind][0]) not in pairs:
                errors.append(f'VOICES {kind} {sex}: no {KINDS[kind][0]} row of house_animations.txt pairs sound base '
                              f'{base} with portrait {portrait}')
            name = sounds.get(str(base + 1))
            if name is None or f'{name.lower()}.wav' not in files:
                errors.append(f'VOICES {kind} {sex}: greeting {base + 1} has no sound file')
    return errors


def voice_errors():
    """D-165 on the installed tables: every house whose owner greets (house_animations' sound base) speaks in a voice
    of the owner's sex, and VOICES holds (voice_source_errors). [error lines]"""
    owners = {npc['id']: npc for town in load_towns() for npc in town.get('npcs', [])}
    sexes = voice_sexes()
    errors = voice_source_errors()
    for row in read_world_table('house_animations.txt'):
        if not row[0].isdigit() or len(row) < 9 or not row[7].strip():
            continue
        base, picture = int(row[7]), int(row[8] or 0)
        owner = owners.get(picture - PORTRAIT_BASE)
        voice_sex = sexes.get(base)
        if voice_sex is None:
            errors.append(f'house {row[0]} {row[2]}: sound base {base} is no voice of VOICES')
        elif owner is None:
            errors.append(f'house {row[0]} {row[2]}: greets in sound base {base} but has no owner')
        elif owner.get('sex') != voice_sex:
            errors.append(f'house {row[0]} {row[2]}: a {voice_sex} voice ({base}) for {owner["name"]}, '
                          f'sex {owner.get("sex")}')
    return errors


